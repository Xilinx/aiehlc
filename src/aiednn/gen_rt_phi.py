"""Writes aiednn_rt_phi.h: the standard normal CDF Phi(x) = (1 + erf(x / sqrt 2)) / 2 on [0, 9)
as 18 degree-9 polynomials in (x - interval centre), fitted at Chebyshev nodes against
math.erf / erfc. Max abs error 4.5e-14 (printed). GELU = x * Phi(x) evaluates without libm
erf / exp: newlib's erf cost ~140 ns per element on the A72 (convnext_tiny's epilogue 1.5 s).

    python3 src/aiednn/gen_rt_phi.py      # rewrites src/aiednn/aiednn_rt_phi.h
"""
import math
from pathlib import Path

import numpy as np

W, NI, DEG = 0.5, 18, 9


def phi(x: float) -> float:
    return 0.5 * (1.0 + math.erf(x / math.sqrt(2.0))) if x < 5 else 1.0 - 0.5 * math.erfc(x / math.sqrt(2.0))


def main() -> None:
    rows, worst = [], 0.0
    for i in range(NI):
        c = (i + 0.5) * W
        t = 0.5 * W * np.cos(np.pi * (np.arange(200) + 0.5) / 200)
        co = np.polynomial.polynomial.polyfit(t, [phi(c + v) for v in t], DEG)
        tt = np.linspace(-W / 2, W / 2, 4001)
        worst = max(worst, max(abs(np.polynomial.polynomial.polyval(v, co) - phi(c + v)) for v in tt))
        rows.append(co)
    out = Path(__file__).with_name("aiednn_rt_phi.h")
    body = "\n".join("    {" + ", ".join(repr(float(v)) for v in co) + "}," for co in rows)
    out.write_text(f"""/* Generated by gen_rt_phi.py -- do not edit. Phi(x) on [i*W, (i+1)*W) =
 * sum_k rt_phi_c[i][k] * (x - (i + 0.5) * W)^k, max abs error {worst:.1e}. */
#ifndef AIEDNN_RT_PHI_H
#define AIEDNN_RT_PHI_H

#define RT_PHI_W {W}
#define RT_PHI_N {NI}
#define RT_PHI_DEG {DEG}
static const double rt_phi_c[RT_PHI_N][RT_PHI_DEG + 1] = {{
{body}
}};

/* the standard normal CDF; 1 beyond 9 (1 - 1.1e-19) */
static inline double rt_phi(double x) {{
    const double ax = x < 0 ? -x : x;
    double p = 1.0;
    if (ax < RT_PHI_W * RT_PHI_N) {{
        const int i = (int)(ax * (1.0 / RT_PHI_W));
        const double t = ax - (i + 0.5) * RT_PHI_W, *c = rt_phi_c[i];
        p = c[RT_PHI_DEG];
        for (int k = RT_PHI_DEG - 1; k >= 0; k--)
            p = p * t + c[k];
    }}
    return x < 0 ? 1.0 - p : p;
}}

#endif /* AIEDNN_RT_PHI_H */
""")
    print(f"{out}: max abs error {worst:.2e}")


if __name__ == "__main__":
    main()
