static int s_core_perf_probe_valid = 0;
static XAie_LocType s_core_perf_probe_tile;
static XAie_DevInst *s_core_perf_probe_dev = NULL;

AieRC __Runtime_core_perf_setup(XAie_DevInst *dev, XAie_LocType tile) {
    AieRC rc;
    rc = XAie_PerfCounterSet(dev, tile, XAIE_CORE_MOD, 0, 0);
    if (rc != XAIE_OK)
        return rc;
    rc = XAie_PerfCounterControlSet(dev, tile, XAIE_CORE_MOD, 0, XAIE_EVENT_ACTIVE_CORE, XAIE_EVENT_ACTIVE_CORE);
    if (rc != XAIE_OK)
        return rc;
    rc = XAie_PerfCounterSet(dev, tile, XAIE_CORE_MOD, 1, 0);
    if (rc != XAIE_OK)
        return rc;
    rc = XAie_PerfCounterControlSet(dev, tile, XAIE_CORE_MOD, 1, XAIE_EVENT_INSTR_VECTOR_CORE,
                                    XAIE_EVENT_INSTR_VECTOR_CORE);
    if (rc != XAIE_OK)
        return rc;
    rc = XAie_PerfCounterSet(dev, tile, XAIE_CORE_MOD, 2, 0);
    if (rc != XAIE_OK)
        return rc;
    rc = XAie_PerfCounterControlSet(dev, tile, XAIE_CORE_MOD, 2, XAIE_EVENT_STREAM_STALL_CORE,
                                    XAIE_EVENT_STREAM_STALL_CORE);
    if (rc != XAIE_OK)
        return rc;
    rc = XAie_PerfCounterSet(dev, tile, XAIE_CORE_MOD, 3, 0);
    if (rc != XAIE_OK)
        return rc;
    rc =
        XAie_PerfCounterControlSet(dev, tile, XAIE_CORE_MOD, 3, XAIE_EVENT_LOCK_STALL_CORE, XAIE_EVENT_LOCK_STALL_CORE);
    if (rc != XAIE_OK)
        return rc;
    AIEHLC_LOG(printf("[aie_runtime] core_perf_setup OK tile(%u,%u)\n", (unsigned)tile.Col, (unsigned)tile.Row));
    return XAIE_OK;
}

int __Runtime_core_perf_probe_valid(void) { return s_core_perf_probe_valid; }

void __Runtime_core_perf_read_probe(uint32_t *active, uint32_t *vec_instr, uint32_t *stream_stall,
                                    uint32_t *lock_stall) {
    if (!s_core_perf_probe_valid) {
        if (active)
            *active = 0;
        if (vec_instr)
            *vec_instr = 0;
        if (stream_stall)
            *stream_stall = 0;
        if (lock_stall)
            *lock_stall = 0;
        return;
    }
    XAie_LocType tile = s_core_perf_probe_tile;
    XAie_DevInst *dev = s_core_perf_probe_dev;
    if (active)
        XAie_PerfCounterGet(dev, tile, XAIE_CORE_MOD, 0, active);
    if (vec_instr)
        XAie_PerfCounterGet(dev, tile, XAIE_CORE_MOD, 1, vec_instr);
    if (stream_stall)
        XAie_PerfCounterGet(dev, tile, XAIE_CORE_MOD, 2, stream_stall);
    if (lock_stall)
        XAie_PerfCounterGet(dev, tile, XAIE_CORE_MOD, 3, lock_stall);
}

void __Runtime_perfcnt_read_mm2s_probe(uint32_t *ch0, uint32_t *ch1) {
    if (!s_core_perf_probe_valid) {
        if (ch0)
            *ch0 = 0;
        if (ch1)
            *ch1 = 0;
        return;
    }
    XAie_LocType tile = s_core_perf_probe_tile;
    XAie_DevInst *dev = s_core_perf_probe_dev;
    if (ch0)
        __Runtime_perfcnt_read(dev, tile, 0, ch0);
    if (ch1)
        __Runtime_perfcnt_read(dev, tile, 1, ch1);
}

/* ---------------------------------------------------------------------------
 * Core event trace: capture an ACTIVE/stall timeline from a core tile and drain
 * it DOWN through the intervening core tiles into the same-column top MemTile's
 * memory via a circuit-switched TRACE -> (SOUTH/NORTH hops) -> S2MM DMA path,
 * then read it back from the MemTile and decode on the host.
 *
 * Why a MemTile and not the core's own data memory: the MemTile has far more
 * memory (512 KB on AIE2PS vs the core tile's small data mem), so a deep trace
 * no longer has to steal space from kernel data.
 *
 * Flow (per the AIE2/AIE2PS core module trace unit):
 *   1. TraceControlConfig: window = ENABLE_CORE .. DISABLE_CORE, mode
 *      EVENT_TIME so packets carry delta-cycles (not PC, not instr count).
 *   2. TraceEvent slots 0..3 = ACTIVE / LOCK_STALL / STREAM_STALL / MEMORY_STALL.
 *   3. Multi-hop circuit-switched route on ONE physical stream channel `strm_ch`
 *      (a tile's SOUTH master port k IS the NORTH slave port k of the tile below,
 *      so the same index chains cleanly). `strm_ch` must be 0..3 (core SOUTH-
 *      master / NORTH-slave and MemTile NORTH-slave port range):
 *        3a. source core tile:  TRACE port 0     -> SOUTH master strm_ch
 *        3b. each intervening core tile: NORTH slave strm_ch -> SOUTH master strm_ch
 *        3c. top MemTile:       NORTH slave strm_ch -> DMA master (S2MM `s2mm_ch`)
 *   4. S2MM BD -> [buf_addr, buf_len) in the MemTile's memory, then enable the
 *      channel. `buf_addr`/`buf_len` are bytes into MemTile memory; buf_addr is
 *      the DMA-view address, the same value __Runtime_core_trace_read passes to
 *      XAie_DataMemBlockRead for the MemTile loc.
 *
 * NOTE: the MemTile DMA-port index is taken to equal `s2mm_ch` (mirrors the
 * single-hop TRACE->DMA convention this replaces). Like the packet decode
 * below, that mapping is worth confirming against one HW capture.
 *
 * The caller MUST reserve [buf_addr, buf_addr+buf_len) in MemTile memory and a
 * free `strm_ch`/`s2mm_ch`, and MUST call this BEFORE enabling the core. Trace
 * only flushes once the core disables (DISABLE_CORE closes the window), so read
 * back with __Runtime_core_trace_read (passing the MemTile loc) after
 * XAie_CoreWaitForDone + XAie_CoreDisable.
 * ------------------------------------------------------------------------- */

/* Slot -> event name, for the decoder. Order must match the TraceEvent slots
 * programmed in __Runtime_core_trace_setup: 0..3 are core-state events, 4..6 are
 * the stream-switch port-0 event group, slot 7 is unused. */
#define AIE_CORE_TRACE_NSLOTS 7u /* slots 0..6 programmed; unit has 8 slots */
static const char *const s_core_trace_slot_name[8] = {"ACTIVE",      "LOCK_STALL",     "STREAM_STALL",   "MEMORY_STALL",
                                                      "PORT_IDLE_0", "PORT_RUNNING_0", "PORT_STALLED_0", "EVENT7"};

/* Slot -> event name for the MEMORY-module trace stream (packet id 2), decoded
 * with these names when a pkt-id-2 stream is present in the shared buffer. Order
 * MUST match the slot events programmed in mem_trace_program_unit: 0 DMA start,
 * 1 DMA finish, 2 DMA lock stall, 3 stream stall (S2MM starvation / MM2S
 * backpressure), 4 memory backpressure (S2MM) / starvation (MM2S), 5 lock group,
 * 6 lock acquire (SEL0 ACQ_GE), 7 lock release (LOCK_0_REL, event 46 -- valid on
 * the compute-tile mem module for both AIE-ML and AIE2PS). The channel/direction
 * is carried in the emitted [TRACESTREAMCONFIG] line, so these names stay
 * channel-generic. */
#define AIE_MEM_TRACE_NSLOTS 8u /* all 8 slots programmed */
static const char *const s_mem_trace_slot_name[8] = {"DMA_START", "DMA_FINISH", "DMA_STALL_LOCK", "STREAM_STALL",
                                                     "MEM_BP",    "LOCK_GRP",   "LOCK_ACQ",       "LOCK_REL"};

/* Slot -> PHYSICAL hardware event id, parallel to the two name tables above, so
 * the decoder can print the real trace-unit event number beside each name
 * ("STREAM_STALL{event value 45}"). These MUST be the per-module hardware event
 * ids (0..127, the value the trace unit actually emits) -- NOT the flat global
 * XAie_Events enum index, which runs into the hundreds for mem-tile DMA events
 * (e.g. XAIE_EVENT_DMA_S2MM_0_STALLED_LOCK_MEM ~374). Both tables are therefore
 * filled at trace-setup time via XAie_EventLogicalToPhysicalConv (see
 * trace_fill_event_labels), from the events actually programmed into the slots.
 * They reflect the MOST RECENT trace setup; when several tiles trace DIFFERENT
 * DMAs the values reflect the last-armed tile (the common single-DMA-per-tile
 * case is exact). Zero until the corresponding *_trace setup runs. */
static uint16_t s_core_trace_slot_event[8]; /* filled at core trace setup */
static uint16_t s_mem_trace_slot_event[8];  /* filled at mem trace setup */

/* Slot -> the driver's SPECIFIC event name for the MEMORY-module stream (e.g.
 * "DMA_MM2S_0_STALLED_LOCK_MEM"), filled at mem_trace_program_unit time from
 * XAie_EventGetString on the actually-programmed events. The static
 * s_mem_trace_slot_name table above stays channel/direction-generic (used by the
 * standalone decoder + Python reference model, which cannot know the watched
 * DMA); the [TIMESYNC] dump prefers this specific name when present and falls
 * back to the generic label otherwise (e.g. in the decoder unit-test harness,
 * where setup never runs so these stay NULL). */
static const char *s_mem_trace_slot_dynname[8];

#ifdef AIE_HAVE_RESOURCE_MAP
/* -------------------------------------------------------------------------
 * Resource-map queries for core-trace channel selection. Each helper scans the
 * flat __aie_resource_map table (passed in as rm[0..n)) filtered by (col,row)
 * and answers whether a given port / packet id / DMA channel is already used by
 * the data-plane routing. Absent map (raw/single-kernel flow) -> not compiled;
 * the caller falls back to convention values.
 * ------------------------------------------------------------------------- */

/* Any MASTER-side port on (col,row) equal to (dir,idx)? Master-side = a
 * packet forward_master or a generic circuit/shim master port. */
static int resmap_master_used(const struct AieResourceEntry *rm, int n, int col, int row, const char *dir, int idx) {
    for (int i = 0; i < n; i++) {
        const struct AieResourceEntry *e = &rm[i];
        if (e->col != col || e->row != row)
            continue;
        if (e->fwd_dir && strcmp(e->fwd_dir, dir) == 0 && e->fwd_idx == idx)
            return 1;
        if (e->master_dir && strcmp(e->master_dir, dir) == 0 && e->master_idx == idx)
            return 1;
    }
    return 0;
}

/* Any SLAVE-side port on (col,row) equal to (dir,idx)? Slave-side = a packet
 * recv_slave or local_dma slot, or a generic circuit/shim slave port. */
static int resmap_slave_used(const struct AieResourceEntry *rm, int n, int col, int row, const char *dir, int idx) {
    for (int i = 0; i < n; i++) {
        const struct AieResourceEntry *e = &rm[i];
        if (e->col != col || e->row != row)
            continue;
        if (e->recv_dir && strcmp(e->recv_dir, dir) == 0 && e->recv_idx == idx)
            return 1;
        if (e->dma_dir && strcmp(e->dma_dir, dir) == 0 && e->dma_idx == idx)
            return 1;
        if (e->slave_dir && strcmp(e->slave_dir, dir) == 0 && e->slave_idx == idx)
            return 1;
    }
    return 0;
}

/* Is packet id `id` already used on (col,row) (recv or dma slot)? */
static int resmap_pktid_used(const struct AieResourceEntry *rm, int n, int col, int row, int id) {
    for (int i = 0; i < n; i++) {
        const struct AieResourceEntry *e = &rm[i];
        if (e->col != col || e->row != row)
            continue;
        if (e->recv_pktid == id || e->dma_pktid == id)
            return 1;
    }
    return 0;
}

/* Is packet arbiter `arb` already used on (col,row) by any data-plane slave
 * slot (recv/dma) or forward master? Used to dedicate a whole arbiter to the
 * trace stream so no data slave/master can share it. */
static int resmap_arbiter_used(const struct AieResourceEntry *rm, int n, int col, int row, int arb) {
    for (int i = 0; i < n; i++) {
        const struct AieResourceEntry *e = &rm[i];
        if (e->col != col || e->row != row)
            continue;
        /* only packet_connect rows carry arbiter fields; circuit rows leave
         * them at 0, so guard on the matching port being present (idx>=0). */
        if (e->recv_idx >= 0 && e->recv_arbiter == arb)
            return 1;
        if (e->dma_idx >= 0 && e->dma_arbiter == arb)
            return 1;
        if (e->fwd_idx >= 0 && e->fwd_arbiter == arb)
            return 1;
    }
    return 0;
}

/* Is MemTile DMA channel `ch` already used on (col,row)? Any recorded port whose
 * direction is "DMA" with idx==ch. */
static int resmap_dma_used(const struct AieResourceEntry *rm, int n, int col, int row, int ch) {
    for (int i = 0; i < n; i++) {
        const struct AieResourceEntry *e = &rm[i];
        if (e->col != col || e->row != row)
            continue;
        if (e->recv_dir && strcmp(e->recv_dir, "DMA") == 0 && e->recv_idx == ch)
            return 1;
        if (e->dma_dir && strcmp(e->dma_dir, "DMA") == 0 && e->dma_idx == ch)
            return 1;
        if (e->fwd_dir && strcmp(e->fwd_dir, "DMA") == 0 && e->fwd_idx == ch)
            return 1;
        if (e->slave_dir && strcmp(e->slave_dir, "DMA") == 0 && e->slave_idx == ch)
            return 1;
        if (e->master_dir && strcmp(e->master_dir, "DMA") == 0 && e->master_idx == ch)
            return 1;
    }
    return 0;
}

/* Reverse of strm_port_type_name for the UPPERCASE direction strings the
 * resource map stores ("DMA","SOUTH","WEST","NORTH","EAST","CORE","TRACE",...).
 * Enum order per xaiegbl.h: CORE=0,DMA,CTRL,FIFO,SOUTH,WEST,NORTH,EAST,TRACE,
 * UCTRLR. Returns SS_PORT_TYPE_MAX when the string is NULL or unrecognized. */
static StrmSwPortType resmap_dir_to_port_type(const char *dir) {
    if (!dir)
        return SS_PORT_TYPE_MAX;
    if (strcmp(dir, "CORE") == 0)
        return CORE;
    if (strcmp(dir, "DMA") == 0)
        return DMA;
    if (strcmp(dir, "CTRL") == 0)
        return CTRL;
    if (strcmp(dir, "FIFO") == 0)
        return FIFO;
    if (strcmp(dir, "SOUTH") == 0)
        return SOUTH;
    if (strcmp(dir, "WEST") == 0)
        return WEST;
    if (strcmp(dir, "NORTH") == 0)
        return NORTH;
    if (strcmp(dir, "EAST") == 0)
        return EAST;
    if (strcmp(dir, "TRACE") == 0)
        return TRACE;
    return SS_PORT_TYPE_MAX;
}

/* Resolve the routed stream-switch port that carries mem-DMA (kind,ch) on
 * (col,row) so the trace event port can watch the REAL data link instead of the
 * trace-stream ingress. mem_dma_kind is AIE_TRACE_DMA_MM2S / _S2MM.
 *   MM2S ch = a DMA SLAVE injection -> the routed link is its MASTER egress:
 *     packet_connect  dma_dir=="DMA"   && dma_idx==ch    -> MASTER fwd_dir:fwd_idx
 *     circuit_connect slave_dir=="DMA" && slave_idx==ch  -> MASTER master_dir:master_idx
 *   S2MM ch = a DMA MASTER drain -> the routed link is its SLAVE ingress:
 *     circuit_connect master_dir=="DMA" && master_idx==ch -> SLAVE slave_dir:slave_idx
 *     packet_connect  dma_dir=="DMA"    && dma_idx==ch     -> SLAVE recv_dir:recv_idx
 * Returns 1 with out_intf/out_type/out_idx set on the first hit whose dir maps
 * to a real port type, else 0 (caller keeps its fallback). */
static int resmap_lookup_dma_port(const struct AieResourceEntry *rm, int n, int col, int row, int mem_dma_kind,
                                  int mem_dma_ch, XAie_StrmPortIntf *out_intf, StrmSwPortType *out_type, int *out_idx) {
    for (int i = 0; i < n; i++) {
        const struct AieResourceEntry *e = &rm[i];
        if (e->col != col || e->row != row)
            continue;
        const char *dir = 0;
        int idx = -1;
        XAie_StrmPortIntf intf;
        if (mem_dma_kind == AIE_TRACE_DMA_MM2S) {
            intf = XAIE_STRMSW_MASTER;
            if (e->dma_dir && strcmp(e->dma_dir, "DMA") == 0 && e->dma_idx == mem_dma_ch && e->fwd_idx >= 0) {
                dir = e->fwd_dir;
                idx = e->fwd_idx;
            } else if (e->slave_dir && strcmp(e->slave_dir, "DMA") == 0 && e->slave_idx == mem_dma_ch) {
                dir = e->master_dir;
                idx = e->master_idx;
            }
        } else {
            intf = XAIE_STRMSW_SLAVE;
            if (e->master_dir && strcmp(e->master_dir, "DMA") == 0 && e->master_idx == mem_dma_ch) {
                dir = e->slave_dir;
                idx = e->slave_idx;
            } else if (e->dma_dir && strcmp(e->dma_dir, "DMA") == 0 && e->dma_idx == mem_dma_ch && e->recv_idx >= 0) {
                dir = e->recv_dir;
                idx = e->recv_idx;
            }
        }
        if (!dir || idx < 0)
            continue;
        StrmSwPortType t = resmap_dir_to_port_type(dir);
        if (t == SS_PORT_TYPE_MAX)
            continue;
        *out_intf = intf;
        *out_type = t;
        *out_idx = idx;
        return 1;
    }
    return 0;
}

/* Per-column record of trace stream / S2MM channels already handed out by
 * earlier trace setups in THIS run. The const data-plane map cannot record the
 * trace's own usage, so without this two traced tiles in the same column would
 * re-pick the same first-free strm_ch / s2mm_ch and collide on the shared
 * pass-through segment and MemTile NORTH-slave / S2MM channel. `col` is
 * partition-relative and bounded by AIE_TRACE_MAX_COLS (64, defined later near
 * _begin_ch); keep the same width here. Indices out of range simply skip the
 * claim check (the map + convention slot allocation still apply). */
#define AIE_TRACE_CLAIM_COLS 64
static uint8_t s_trace_strm_claim[AIE_TRACE_CLAIM_COLS]; /* bit ch => strm_ch ch taken on this col's route  */
static uint8_t s_trace_s2mm_claim[AIE_TRACE_CLAIM_COLS]; /* bit ch => s2mm_ch ch taken on this col's memtile */

static int resmap_strm_claimed(int col, int ch) {
    return (col >= 0 && col < AIE_TRACE_CLAIM_COLS) ? (s_trace_strm_claim[col] & (1u << ch)) != 0 : 0;
}
static int resmap_s2mm_claimed(int col, int ch) {
    return (col >= 0 && col < AIE_TRACE_CLAIM_COLS) ? (s_trace_s2mm_claim[col] & (1u << ch)) != 0 : 0;
}
/* Record the resources this trace setup consumed so later picks avoid them. */
static void resmap_claim_trace(int col, uint8_t strm, uint8_t s2mm) {
    if (col < 0 || col >= AIE_TRACE_CLAIM_COLS)
        return;
    s_trace_strm_claim[col] |= (uint8_t)(1u << strm);
    s_trace_s2mm_claim[col] |= (uint8_t)(1u << s2mm);
}

/* Pick a stream channel / MemTile S2MM channel / packet id / BD for the core
 * trace route that avoid the data-plane ports the map records for this column
 * AND the trace resources earlier setups in this run already claimed.
 * Returns 1 with the out params written, or 0 (caller keeps convention values)
 * when no free candidate exists. srcRow is the source core row, mtRow the top
 * MemTile row (srcRow > pass-through rows > mtRow). Physical channel sharing: an
 * upper tile's SOUTH master idx IS the NORTH slave idx of the tile below, so a
 * free strm_ch must clear SOUTH-master on the source, NORTH-slave + SOUTH-master
 * on every pass-through core, and NORTH-slave on the MemTile.
 *
 * NOTE: the map records no BDs, so a trace BD colliding with a data-plane DMA BD
 * is NOT detectable here; the BD is chosen parity-correct (MemTile channel rule)
 * and distinct per channel, matching today's convention (see _begin_ch). */
static int resmap_pick_trace_resources(const struct AieResourceEntry *rm, int n, int col, uint8_t srcRow, uint8_t mtRow,
                                       uint8_t *out_strm, uint8_t *out_s2mm, uint8_t *out_bd, uint8_t *out_pkt,
                                       uint8_t *out_arb, uint8_t *out_msel, uint8_t *out_mselen) {
    /* Core SOUTH-master / NORTH-slave and MemTile NORTH-slave ports are 0..3
     * (== AIE_TRACE_SLOTS_PER_COL, defined later near _begin_ch). */
    enum { TRACE_STRM_CH_RANGE = 4 };
    int strm = -1;
    for (int ch = 0; ch < TRACE_STRM_CH_RANGE; ch++) {
        if (resmap_strm_claimed(col, ch) || resmap_master_used(rm, n, col, srcRow, "SOUTH", ch))
            continue;
        int ok = 1;
        for (uint8_t r = (uint8_t)(srcRow - 1); r > mtRow && ok; r--)
            if (resmap_slave_used(rm, n, col, r, "NORTH", ch) || resmap_master_used(rm, n, col, r, "SOUTH", ch))
                ok = 0;
        if (!ok)
            continue;
        if (resmap_slave_used(rm, n, col, mtRow, "NORTH", ch))
            continue;
        strm = ch;
        break;
    }
    if (strm < 0)
        return 0;

    int s2mm = -1;
    for (int ch = 0; ch < TRACE_STRM_CH_RANGE; ch++)
        if (!resmap_s2mm_claimed(col, ch) && !resmap_dma_used(rm, n, col, mtRow, ch)) {
            s2mm = ch;
            break;
        }
    if (s2mm < 0)
        return 0;

    int pkt = -1;
    for (int id = 1; id < 32; id++)
        if (!resmap_pktid_used(rm, n, col, srcRow, id)) {
            pkt = id;
            break;
        }
    if (pkt < 0)
        return 0;

    /* Dedicate a WHOLE packet arbiter to the trace stream on the source tile:
     * pick the lowest arbiter (0..XAIE_SS_ARBITOR_MAX==7) used by NO data-plane
     * recv/dma slave slot and NO forward master on this tile. With the arbiter
     * exclusive, msel=0 is unambiguous and MSelEn = (1 << msel) reaches only the
     * trace master. If none is free, fail the whole pick so the caller keeps the
     * convention value (arbiter=1) and warns. */
    enum { TRACE_ARB_MAX = 7 };
    int arb = -1;
    for (int a = 0; a <= TRACE_ARB_MAX; a++)
        if (!resmap_arbiter_used(rm, n, col, srcRow, a)) {
            arb = a;
            break;
        }
    if (arb < 0)
        return 0;

    /* Parity-correct + distinct-per-channel BD (MemTile rule: even ch -> BD<24,
     * odd ch -> BD>=24). Matches convention k_bd_for_slot {4,25,6,27}: even ch
     * -> 4+ch, odd ch -> 24+ch. Distinct s2mm (enforced above) => distinct BD. */
    *out_bd = ((s2mm % 2) == 0) ? (uint8_t)(4 + s2mm) : (uint8_t)(24 + s2mm);
    *out_strm = (uint8_t)strm;
    *out_s2mm = (uint8_t)s2mm;
    *out_pkt = (uint8_t)pkt;
    *out_arb = (uint8_t)arb;
    *out_msel = 0;
    *out_mselen = (uint8_t)(1u << *out_msel);
    return 1;
}

/* Apply map-driven selection for the source `tile`: on success overwrite
 * *strm/*s2mm/*bd/*pkt with collision-free values, otherwise leave them (the
 * caller's convention fallback) and warn. This ONLY selects -- the claim is
 * recorded later, once the stream connections actually succeed (see
 * resmap_claim_trace at the end of section 3 in __Runtime_core_trace_setup), so a
 * route that fails part-way does not leak a claim on a channel it never occupied.
 * Keeps __Runtime_core_trace_setup short (CLAUDE 200-line rule). No-op when the
 * map is absent/empty. */
static void resmap_apply_trace_resources(const struct AieResourceEntry *rm, int n, XAie_LocType tile, uint8_t mt_row,
                                         uint8_t *strm, uint8_t *s2mm, uint8_t *bd, uint8_t *pkt, uint8_t *arb,
                                         uint8_t *msel, uint8_t *mselen) {
    if (!rm || n <= 0)
        return;
    uint8_t p_strm, p_s2mm, p_bd, p_pkt, p_arb, p_msel, p_mselen;
    if (resmap_pick_trace_resources(rm, n, (int)tile.Col, tile.Row, mt_row, &p_strm, &p_s2mm, &p_bd, &p_pkt, &p_arb,
                                    &p_msel, &p_mselen)) {
        *strm = p_strm;
        *s2mm = p_s2mm;
        *bd = p_bd;
        *pkt = p_pkt;
        *arb = p_arb;
        *msel = p_msel;
        *mselen = p_mselen;
        printf("[aie_runtime] core_trace_setup: resource-map picked strm_ch=%u s2mm_ch=%u bd=%u pkt_id=%u arbiter=%u "
               "msel=%u mselen=%u tile(%u,%u)\n",
               (unsigned)*strm, (unsigned)*s2mm, (unsigned)*bd, (unsigned)*pkt, (unsigned)*arb, (unsigned)*msel,
               (unsigned)*mselen, (unsigned)tile.Col, (unsigned)tile.Row);
    } else {
        printf("[aie_runtime] core_trace_setup: resource-map found no free trace resources; keeping convention "
               "strm_ch=%u s2mm_ch=%u bd=%u tile(%u,%u)\n",
               (unsigned)*strm, (unsigned)*s2mm, (unsigned)*bd, (unsigned)tile.Col, (unsigned)tile.Row);
    }
}
#endif /* AIE_HAVE_RESOURCE_MAP */

