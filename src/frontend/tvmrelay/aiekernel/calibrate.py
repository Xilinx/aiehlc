"""CALIBRATE: the user's reference vs TVM's own kernel, layer by layer, on x86.

For every matched call this links ONE x86 program from

* the layer's stage-5 TVM C (``layers/NN_op/NN_op.c``) -- the ground truth,
  exactly the code ``main_local.elf`` runs;
* the user's ``<entry>_ref`` (the spec's ``reference`` file);
* a fixed harness (below) that feeds both the SAME arguments and dumps both
  outputs.

Inputs are the call's REAL constants from ``params.bin`` (weights, bias, the
quant params ``require=`` was checked on), plus activations that are not real
but adversarial: two seeded uniform draws over the dtype's full range, then
all-minimum and all-maximum (the requantize clamps and accumulator extremes).
A reference that matches on those matches for structural reasons, not by luck
of the data. The whole-network run with real activations is ``emulate``.

Outputs are poisoned with DIFFERENT bytes before each side runs, so an element
the reference forgets to write cannot pass by inheriting TVM's value.

Why the reference and not the AIE kernel: the AIE kernel cannot run here. What
CAN be proven here is the hard part of every bring-up so far -- layouts
(OIHW3i4o / NCHW4c), the two zero-point terms, the requant rounding, int32 vs
int16 accumulation. The tutorial's rule: calibrate the reference first, then
make the AIE kernel match the reference (``conv2d_stem_verify`` pattern).
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

from .hostbuild import (REPO, HostBuildError, compile_c, host_dir, link, run)
from .spec import DTYPES

__all__ = ["CalibResult", "calibrate_layer", "calibrate"]

_HARNESS = r"""
/* Generated by frontend/tvmrelay/aiekernel/calibrate.py -- do not edit.
 * argv: sig.txt inputs.bin out_tvm.bin out_ref.bin
 * sig.txt: N, then per arg "is_out code bits ndim d0 .. d{ndim-1} nbytes". */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "tvm_graph_types.h"
#include "aie_user_kernel.h"

int32_t AIEK_TVM_FN(void *, int32_t *, int32_t, void *, int32_t *, void *);
int AIEK_REF_FN(const aiek_tensor *, int);
void tvm_shim_workspace_init(void *buf, uint64_t bytes);

#define MAXA 32
static int64_t shape[MAXA][AIEK_MAX_NDIM];
static int is_out[MAXA], code[MAXA], bits[MAXA], ndim[MAXA];
static uint64_t nbytes[MAXA];
static void *buf[MAXA];

static int dump(const char *path, int n, int poison_only) {
    FILE *f = fopen(path, "wb");
    if (!f) return -1;
    for (int i = 0; i < n; i++)
        if (is_out[i] && !poison_only) fwrite(buf[i], 1, nbytes[i], f);
    fclose(f);
    return 0;
}

int main(int argc, char **argv) {
    if (argc != 5) { fprintf(stderr, "usage\n"); return 2; }
    FILE *s = fopen(argv[1], "r"), *in = fopen(argv[2], "rb");
    int n = 0;
    if (!s || !in || fscanf(s, "%d", &n) != 1 || n > MAXA) return 3;
    for (int i = 0; i < n; i++) {
        if (fscanf(s, "%d %d %d %d", &is_out[i], &code[i], &bits[i], &ndim[i]) != 4) return 4;
        for (int k = 0; k < ndim[i]; k++)
            if (fscanf(s, "%lld", (long long *)&shape[i][k]) != 1) return 5;
        if (fscanf(s, "%llu", (unsigned long long *)&nbytes[i]) != 1) return 6;
        buf[i] = aligned_alloc(64, (nbytes[i] + 63) / 64 * 64);
        if (!is_out[i] && fread(buf[i], 1, nbytes[i], in) != nbytes[i]) return 7;
    }
    static uint8_t ws[64u << 20];
    tvm_shim_workspace_init(ws, sizeof ws);

    DLTensor dl[MAXA]; TVMValue v[MAXA]; int32_t codes[MAXA];
    for (int i = 0; i < n; i++) {
        memset(&dl[i], 0, sizeof dl[i]);
        dl[i].data = buf[i]; dl[i].device.device_type = 1; dl[i].ndim = ndim[i];
        dl[i].dtype.code = (uint8_t)code[i]; dl[i].dtype.bits = (uint8_t)bits[i];
        dl[i].dtype.lanes = 1; dl[i].shape = shape[i];
        v[i].v_handle = &dl[i]; codes[i] = 7;
        if (is_out[i]) memset(buf[i], 0xA5, nbytes[i]);
    }
    int rc_tvm = AIEK_TVM_FN(v, codes, n, 0, 0, 0);
    if (dump(argv[3], n, 0)) return 8;

    aiek_tensor t[MAXA];
    for (int i = 0; i < n; i++) {
        t[i].data = buf[i]; t[i].ndim = ndim[i]; t[i].code = (uint8_t)code[i];
        t[i].bits = (uint8_t)bits[i]; t[i].lanes = 1; t[i].shape = shape[i];
        t[i].nbytes = nbytes[i];
        if (is_out[i]) memset(buf[i], 0x5A, nbytes[i]);
    }
    int rc_ref = AIEK_REF_FN(t, n);
    if (dump(argv[4], n, 0)) return 9;
    printf("AIEK_CALIB rc_tvm=%d rc_ref=%d\n", rc_tvm, rc_ref);
    return 0;
}
"""


@dataclass
class CalibResult:
    layer: int
    call: int
    symbol: str
    ok: bool
    trials: list = field(default_factory=list)   # per trial: dict
    error: str = ""

    def summary(self) -> str:
        if self.error:
            return f"layer {self.layer:02d} call [{self.call:02d}]: ERROR {self.error}"
        bad = [t for t in self.trials if not t["ok"]]
        if not bad:
            n = sum(o["elems"] for o in self.trials[0]["outputs"]) if self.trials else 0
            return (f"layer {self.layer:02d} call [{self.call:02d}]: BIT-EXACT on "
                    f"{len(self.trials)} trial(s) x {n:,} outputs "
                    f"({', '.join(t['name'] for t in self.trials)})")
        t = bad[0]
        # A refusal (AIEK_ERR_PARAM ...) leaves the outputs poisoned; the rc is
        # the real story, the mismatch count would only be its echo.
        o = None if t["rc_ref"] or t["rc_tvm"] else \
            next((o for o in t["outputs"] if not o["ok"]), None)
        what = (f"rc tvm={t['rc_tvm']} ref={t['rc_ref']}" if o is None else
                f"{o['mismatches']:,}/{o['elems']:,} outputs differ, max |d|={o['max_abs']}, "
                f"first at {o['first']}")
        return (f"layer {self.layer:02d} call [{self.call:02d}]: MISMATCH in trial "
                f"{t['name']!r}: {what}")


_NP = {"int8": "i1", "uint8": "u1", "int16": "<i2", "uint16": "<u2",
       "int32": "<i4", "uint32": "<u4", "int64": "<i8", "uint64": "<u8",
       "float16": "<f2", "float32": "<f4", "float64": "<f8"}


def _activation(arg, trial: str, rng):
    """Adversarial activation for one ``in`` arg. Wide ints stay within +-2^15
    -- a TVM int32 activation is an accumulator-scale value, and full-range
    random int32 would overflow BOTH sides into agreement-by-wraparound."""
    import numpy as np

    dt = np.dtype(_NP[arg.dtype])
    shape = tuple(int(d) for d in arg.shape)
    if dt.kind == "f":
        if trial in ("min", "max"):
            return np.full(shape, -4.0 if trial == "min" else 4.0, dt)
        return rng.standard_normal(shape).astype(dt)
    info = np.iinfo(dt)
    lo, hi = (max(info.min, -(1 << 15)), min(info.max, 1 << 15)) if dt.itemsize > 2 \
        else (info.min, info.max)
    if trial == "min":
        return np.full(shape, lo, dt)
    if trial == "max":
        return np.full(shape, hi, dt)
    return rng.integers(lo, hi, size=shape, endpoint=True, dtype=np.int64).astype(dt)


def _build(net, spec, call, work: Path) -> Path:
    """Link ``calib_<layer>`` for this (spec, layer). Cached by mtime."""
    hdir = host_dir(net.out_dir)
    layer_c = net.layer_source(call.layer)
    if layer_c is None:
        raise HostBuildError(f"no stage-5 source for layer {call.layer} "
                             f"(layers/manifest.json); re-run deploy_flow.py")
    inc = [hdir, net.out_dir / "layers", REPO / "include"]
    harness = work / "calib_harness.c"
    if not harness.is_file() or harness.read_text() != _HARNESS:
        harness.write_text(_HARNESS)
    objs = [
        compile_c(harness, work / f"harness_L{call.layer:02d}.o", inc,
                  [f"AIEK_TVM_FN={call.symbol}", f"AIEK_REF_FN={spec.entry}_ref"],
                  force=True),
        compile_c(layer_c, net.out_dir / "aiek" / "_host" / "obj" / f"{layer_c.stem}.o", inc),
        compile_c(hdir / "tvm_runtime_shim.c", hdir / "obj" / "tvm_runtime_shim.o", inc),
        compile_c(spec.reference, work / f"{spec.reference.stem}.o",
                  [*inc, spec.reference.parent], force=True),
    ]
    cxx = spec.reference.suffix in (".cc", ".cpp", ".cxx")
    return link(objs, work / f"calib_L{call.layer:02d}", cxx=cxx)


def _compare(net, call, out_tvm: Path, out_ref: Path, spec) -> list:
    import numpy as np

    a_bytes, b_bytes = out_tvm.read_bytes(), out_ref.read_bytes()
    res, off = [], 0
    for targ, arg in zip(call.args, spec.args):
        if targ.kind != "out":
            continue
        dt = np.dtype(_NP[targ.dtype])
        cnt = targ.nbytes // dt.itemsize
        a = np.frombuffer(a_bytes, dt, cnt, off).astype(np.float64 if dt.kind == "f" else np.int64)
        b = np.frombuffer(b_bytes, dt, cnt, off).astype(a.dtype)
        off += targ.nbytes
        diff = np.abs(a - b)
        bad = np.flatnonzero(diff > arg.tol)
        first = (list(int(i) for i in np.unravel_index(int(bad[0]), targ.shape))
                 if bad.size else None)
        res.append({"slot": targ.slot, "elems": int(cnt), "mismatches": int(bad.size),
                    "max_abs": float(diff.max()) if cnt else 0.0, "tol": arg.tol,
                    "first": first, "ok": not bad.size})
    return res


def calibrate_layer(net, spec, calls, trials=("rand0", "rand1", "min", "max"),
                    verbose: bool = False) -> list:
    """Run every trial on every call of one layer. One :class:`CalibResult` per call."""
    import numpy as np

    if spec.reference is None or not Path(spec.reference).is_file():
        return [CalibResult(c.layer, c.call, c.symbol, False,
                            error="spec has no reference file") for c in calls]
    work = net.out_dir / "aiek" / spec.name / "calib"
    work.mkdir(parents=True, exist_ok=True)
    try:
        exe = _build(net, spec, calls[0], work)
    except HostBuildError as exc:
        return [CalibResult(c.layer, c.call, c.symbol, False, error=str(exc)) for c in calls]

    results = []
    for call in calls:
        res = CalibResult(call.layer, call.call, call.symbol, True)
        sig = [str(len(call.args))]
        for a in call.args:
            code, bits = DTYPES[a.dtype]
            sig.append(f"{int(a.kind == 'out')} {code} {bits} {len(a.shape)} "
                       f"{' '.join(str(int(d)) for d in a.shape)} {a.nbytes}")
        (work / "sig.txt").write_text("\n".join(sig) + "\n")
        for k, trial in enumerate(trials):
            rng = np.random.default_rng(1000 + k)
            with open(work / "inputs.bin", "wb") as fh:
                for a in call.args:
                    if a.kind == "param":
                        fh.write(net.param_bytes(a.param))
                    elif a.kind == "in":
                        fh.write(_activation(a, trial, rng).tobytes())
            proc = run([exe, work / "sig.txt", work / "inputs.bin",
                        work / "out_tvm.bin", work / "out_ref.bin"], cwd=work)
            line = next((ln for ln in proc.stdout.splitlines()
                         if ln.startswith("AIEK_CALIB")), "")
            if proc.returncode != 0 or not line:
                res.ok, res.error = False, (f"harness exit {proc.returncode}: "
                                            f"{(proc.stderr or proc.stdout)[-400:]}")
                break
            rcs = dict(tok.split("=") for tok in line.split()[1:])
            outs = _compare(net, call, work / "out_tvm.bin", work / "out_ref.bin", spec)
            ok = int(rcs["rc_ref"]) == 0 and int(rcs["rc_tvm"]) == 0 and all(o["ok"] for o in outs)
            res.trials.append({"name": trial, "rc_tvm": int(rcs["rc_tvm"]),
                               "rc_ref": int(rcs["rc_ref"]), "outputs": outs, "ok": ok})
            res.ok &= ok
        if verbose:
            print(f"  [calib] {res.summary()}")
        results.append(res)
    return results


def calibrate(net, spec, layer_verdicts, verbose: bool = True) -> dict:
    """``{layer: [CalibResult]}`` for every MATCHING layer in *layer_verdicts*."""
    out = {}
    for lv in layer_verdicts:
        if lv.ok:
            out[lv.layer] = calibrate_layer(net, spec, [v.call for v in lv.calls],
                                            verbose=verbose)
    return out
