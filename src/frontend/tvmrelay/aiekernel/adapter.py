"""Generate the TVM packed-call adapter: ``aie_<tvm symbol>()`` -> user entry.

``graph_driver.c`` calls every kernel through TVM's packed ABI
(``int32_t f(void *args, int32_t *codes, int32_t n, ...)``) and, built with
``-DGRAPH_AIE_OFFLOAD``, calls ``aie_<symbol>`` instead of ``<symbol>`` for each
layer ``partition.json`` sends to the AIE (``arm_build.aie_entries``). This
module writes that function, generically, from the spec -- the hand-written
counterpart is ``aie_stem_lib._ENTRY_TMPL``, which knows the stem's nine
arguments by heart.

One template, two callees, so the code that runs on the board is the code that
was tested on x86:

``target="aie"``   appended to aiehlc's ``host.cc`` (C++), calls the user ENTRY,
                   which launches the AIE;
``target="ref"``   compiled with the host gcc (C) by ``emulate``, calls
                   ``<entry>_ref`` -- the whole network then runs on x86 with
                   the reference standing where the AIE will.

The adapter re-checks every argument's dtype and CONCRETE shape (the layer's,
not the spec's wildcards) before calling, because a mismatch here is a wrong-
pointer bug that would otherwise compute plausible garbage.
"""

from __future__ import annotations

from frontend.tvmrelay.aie_stem_lib import entry_symbol

__all__ = ["adapter_source", "ADAPTER_MARK", "entry_symbol"]

#: Marks the appended block in host.cc so a re-install replaces it.
ADAPTER_MARK = "/* ---- aiek adapters: generated by frontend/tvmrelay/aiekernel -- do not edit ---- */"

_DTYPE_CODE = {"int": 0, "uint": 1, "float": 2}


def _code_bits(dtype: str) -> tuple:
    for prefix in ("uint", "int", "float"):
        if dtype.startswith(prefix):
            return _DTYPE_CODE[prefix], int(dtype[len(prefix):])
    raise ValueError(f"unsupported dtype {dtype!r}")


def _short(symbol: str) -> str:
    return symbol.replace("tvmgen_default_fused_", "")[:40]


def adapter_source(spec, call, target: str = "aie", header: bool = True) -> str:
    """C source of ``aie_<call.symbol>`` for *spec*, valid as C11 and C++.

    *call* is any :class:`graph.LayerCall` of the layer -- every call of one
    symbol has the same shapes, which are baked in as the runtime check.
    """
    if target not in ("aie", "ref"):
        raise ValueError(f"target {target!r}: want 'aie' or 'ref'")
    callee = spec.entry if target == "aie" else f"{spec.entry}_ref"
    fn = entry_symbol(call.symbol)
    layer = f"{call.layer:02d}" if call.layer is not None else "??"
    n = len(call.args)
    checks, hashes = [], []
    for a in call.args:
        code, bits = _code_bits(a.dtype)
        dims = ", ".join(str(int(d)) for d in a.shape)
        checks.append(f"    static const int64_t s{a.slot}[] = {{{dims}}};\n"
                      f"    if (aiek_expect(&t[{a.slot}], {a.slot}, {code}, {bits}, "
                      f"{len(a.shape)}, s{a.slot}, who) != AIEK_OK)\n"
                      f"        return -1;")
        if a.kind == "out":
            hashes.append(f"    h = aiek_hash_bytes(t[{a.slot}].data, t[{a.slot}].nbytes, h);")
    first_out = next(a.slot for a in call.args if a.kind == "out")
    # Spec name (what the entry calls it) next to the graph's view (param name).
    sig = "\n".join(f" *   {a.slot:2d} {spec.args[a.slot].name or '-':14s} {a}"
                    for a in call.args)
    head = (f"{ADAPTER_MARK}\n#include \"aie_user_kernel.h\"\n\n") if header else ""
    return f"""{head}/* layer {layer}: {call.symbol}
 * -> {callee}() [{spec.name}], {"AIE" if target == "aie" else "x86 reference"}
{sig}
 */
AIEK_EXTERN_C int {callee}(const aiek_tensor *args, int num_args);

AIEK_EXTERN_C int32_t {fn}(void *args, int32_t *type_codes, int32_t num_args,
                           void *out_ret_value, int32_t *out_ret_tcode,
                           void *resource_handle) {{
    static const char who[] = "layer {layer} {spec.name}";
    aiek_tensor t[{n}];
    uint32_t h = 0;
    (void)type_codes; (void)out_ret_value; (void)out_ret_tcode; (void)resource_handle;
    printf("[aie-offload] layer {layer} {_short(call.symbol)}: ENTER {spec.name} "
           "({callee}), %d args\\n", (int)num_args);
    if (aiek_bind(args, (int)num_args, t, {n}, who) != AIEK_OK)
        return -1;
{chr(10).join(checks)}
    const int rc = {callee}(t, {n});
{chr(10).join(hashes)}
    {{
        static const uint8_t none[8] = {{0}};   /* initialized: a const array must be in C++ */
        const uint8_t *o = t[{first_out}].nbytes >= 8 ? (const uint8_t *)t[{first_out}].data : none;
        printf("[aie-offload] layer {layer}: EXIT rc=%d, out[0..7]= %02x %02x %02x %02x "
               "%02x %02x %02x %02x, hash=%08x\\n", rc, o[0], o[1], o[2], o[3], o[4],
               o[5], o[6], o[7], (unsigned)h);
    }}
    return rc == AIEK_OK ? 0 : -1;
}}
"""
