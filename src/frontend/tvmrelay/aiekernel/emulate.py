"""EMULATE: the whole network on x86 with every selected layer swapped for its
reference, through the generated adapter. Logits must not move.

``calibrate`` proves each reference against its layer in isolation, on
synthetic activations. This proves the INTEGRATION on real ones:

* the driver swap -- the same ``<symbol>`` -> ``aie_<symbol>`` substitution
  ``graph_driver.c`` makes under ``-DGRAPH_AIE_OFFLOAD``, for every call of
  every selected layer (ResNet-18 calls layer 04 twice);
* the generated adapter -- the same text ``build`` appends to ``host.cc``,
  differing only in the callee (``<entry>_ref`` instead of ``<entry>``): arg
  binding, the per-arg dtype/shape checks, the return-code path;
* every reference fed the real upstream activations of the photo.

Two x86 programs are linked from the same objects and differ only in the driver
(and the adapters + references the emulated one adds): a BASELINE running
TVM's kernels everywhere -- what ``main_local.elf`` runs -- and the EMULATED
one. The verdict is a byte compare of the 1000 float logits, plus a count of
``[aie-offload] ... ENTER`` lines per layer against the graph's call count, so
a swap that silently never fired cannot pass.
"""

from __future__ import annotations

import os
import re
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass, field
from pathlib import Path

from .adapter import adapter_source, entry_symbol
from .hostbuild import (REPO, HostBuildError, compile_c, host_dir, link, run)

__all__ = ["EmulResult", "emulate", "swap_driver"]

_MAIN = r"""
/* Generated by frontend/tvmrelay/aiekernel/emulate.py -- do not edit.
 * argv: weights.bin logits.out. Prints one AIEK_EMUL line. */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include "input_image.h"

void graph_init(const uint8_t *params_blob);
float *graph_input(void);
float *graph_run(void);
int graph_output_len(void);

int main(int argc, char **argv) {
    if (argc != 3) return 2;
    FILE *f = fopen(argv[1], "rb");
    if (!f) return 3;
    fseek(f, 0, SEEK_END);
    long n = ftell(f);
    fseek(f, 0, SEEK_SET);
    uint8_t *blob = (uint8_t *)aligned_alloc(64, (size_t)(n + 63) / 64 * 64);
    if (!blob || fread(blob, 1, (size_t)n, f) != (size_t)n) return 4;
    fclose(f);
    graph_init(blob);
    float *in = graph_input();
    for (int i = 0; i < INPUT_IMAGE_ELEMS; ++i) in[i] = input_image[i];
    float *out = graph_run();
    int len = graph_output_len(), best = 0;
    for (int i = 1; i < len; ++i) if (out[i] > out[best]) best = i;
    FILE *o = fopen(argv[2], "wb");
    if (!o) return 5;
    fwrite(out, sizeof(float), (size_t)len, o);
    fclose(o);
    printf("AIEK_EMUL top1=%d logit=%.6f n=%d\n", best, (double)out[best], len);
    return 0;
}
"""


@dataclass
class EmulResult:
    ok: bool
    reason: str = ""
    baseline_top1: tuple = None
    emulated_top1: tuple = None
    logits_identical: bool = False
    max_abs_logit_diff: float = None
    swaps: dict = field(default_factory=dict)   # symbol -> {"expected", "entered", "failed"}

    def summary(self) -> str:
        if not self.ok and self.baseline_top1 is None:
            return f"emulate: FAILED -- {self.reason}"
        swaps = ", ".join(f"{s['label']} x{s['entered']}/{s['expected']}"
                          for s in self.swaps.values())
        verdict = ("logits BIT-IDENTICAL" if self.logits_identical else
                   f"logits differ (max |d| = {self.max_abs_logit_diff:.6g})")
        head = "PASS" if self.ok else "FAIL"
        return (f"emulate: {head} -- {verdict}; top1 baseline {self.baseline_top1} vs "
                f"emulated {self.emulated_top1}; swapped {swaps}"
                + (f"; {self.reason}" if self.reason else ""))


def swap_driver(text: str, symbols) -> tuple:
    """Route every call of *symbols* in ``graph_driver.c`` text to ``aie_<symbol>``.

    Rewrites exactly the call lines ``generate_driver`` emits
    (``    <fn>(args, codes, N, 0, 0, 0);``) and adds the prototypes. Returns
    ``(text, {symbol: substitutions})``.
    """
    counts, protos = {}, []
    for sym in symbols:
        pat = re.compile(rf"^(\s*){re.escape(sym)}(\(args, codes, \d+, 0, 0, 0\);)$", re.M)
        text, n = pat.subn(lambda m: f"{m.group(1)}{entry_symbol(sym)}{m.group(2)}", text)
        counts[sym] = n
        protos.append(f"int32_t {entry_symbol(sym)}(void* args, int32_t* arg_type_ids, "
                      f"int32_t num_args, void* out_ret_value, int32_t* out_ret_tcode, "
                      f"void* resource_handle);")
    marker = '#include "tvm_graph_types.h"\n'
    block = "\n/* aiekernel emulate: layers routed to their x86 reference */\n" + "\n".join(protos) + "\n"
    return text.replace(marker, marker + block, 1), counts


def _ensure_arm_sources(net, verbose: bool) -> Path:
    """``arm_build/`` sources for THIS graph. The driver bakes buffer sizes and
    weights.bin offsets in as literals, so a driver from an earlier graph links
    fine and computes garbage; its ``graph-sha`` stamp says which graph it is."""
    from frontend.tvmrelay.arm_build import build_arm_elf, graph_sha

    arm = net.out_dir / "arm_build"
    driver = arm / "graph_driver.c"
    why = None
    if not driver.is_file() or not (arm / "input_image.h").is_file():
        why = "missing"
    elif f"graph-sha: {graph_sha(net.graph_path)}" not in driver.read_text()[:2000]:
        why = "from a different graph (graph-sha)"
    if why:
        if verbose:
            print(f"  [emul] arm_build/ sources {why} -- regenerating them (no make)")
        build_arm_elf(net.out_dir, c_name=f"{net.stem}.c", run_make=False, verbose=False)
    if not (arm / "graph_driver.c").is_file():
        raise HostBuildError(f"{arm}/graph_driver.c could not be generated")
    return arm


def _layer_objects(net, inc) -> list:
    srcs = sorted((net.out_dir / "layers").glob("*/*.c"))
    if not srcs:
        raise HostBuildError("no layers/*/*.c -- emulate needs the stage-5 split")
    obj = net.out_dir / "aiek" / "_host" / "obj"
    jobs = max(1, (os.cpu_count() or 4))
    with ThreadPoolExecutor(jobs) as pool:
        return list(pool.map(lambda s: compile_c(s, obj / f"{s.stem}.o", inc), srcs))


def emulate(net, swaps, verbose: bool = True, tag: str = "emul") -> EmulResult:
    """Run the network twice on x86 -- TVM kernels everywhere, then with *swaps*
    (``[(spec, [LayerCall, ...]), ...]``, one entry per selected layer)."""
    import numpy as np

    arm = _ensure_arm_sources(net, verbose)
    hdir = host_dir(net.out_dir)
    work = net.out_dir / "aiek" / tag
    work.mkdir(parents=True, exist_ok=True)
    inc = [hdir, arm, net.out_dir / "layers", REPO / "include"]

    common = _layer_objects(net, inc) + [
        compile_c(hdir / "tvm_runtime_shim.c", hdir / "obj" / "tvm_runtime_shim.o", inc)]
    (work / "emul_main.c").write_text(_MAIN)
    common.append(compile_c(work / "emul_main.c", work / "emul_main.o", inc, force=True))

    base_drv = compile_c(arm / "graph_driver.c", work / "graph_driver_base.o", inc)
    driver = arm / "graph_driver.c"
    swapped, counts = swap_driver(driver.read_text(), [c[0].symbol for _, c in swaps])
    (work / "graph_driver_emul.c").write_text(swapped)
    emul_drv = compile_c(work / "graph_driver_emul.c", work / "graph_driver_emul.o", inc, force=True)

    adapters = ['#include "aie_user_kernel.h"\n']
    refs, cxx = {}, False
    for spec, calls in swaps:
        adapters.append(adapter_source(spec, calls[0], target="ref", header=False))
        refs[spec.reference] = spec
        cxx |= spec.reference.suffix in (".cc", ".cpp", ".cxx")
    (work / "aiek_adapters_ref.c").write_text("\n".join(adapters))
    extra = [compile_c(work / "aiek_adapters_ref.c", work / "aiek_adapters_ref.o", inc, force=True)]
    extra += [compile_c(r, work / f"ref_{s.entry}.o", [*inc, r.parent], force=True)
              for r, s in refs.items()]

    base = link([base_drv, *common], work / "net_baseline")
    emul = link([emul_drv, *common, *extra], work / "net_emulated", cxx=cxx)
    weights = arm / "weights.bin"
    outs = {}
    for name, exe in (("baseline", base), ("emulated", emul)):
        proc = run([exe, weights, work / f"logits_{name}.bin"], cwd=work, timeout=1800)
        (work / f"{name}.log").write_text(proc.stdout + proc.stderr)
        line = next((ln for ln in proc.stdout.splitlines() if ln.startswith("AIEK_EMUL")), None)
        if proc.returncode != 0 or line is None:
            return EmulResult(False, f"{name} run exit {proc.returncode}: "
                                     f"{(proc.stderr or proc.stdout)[-300:]}")
        kv = dict(t.split("=") for t in line.split()[1:])
        outs[name] = (proc.stdout, (int(kv["top1"]), float(kv["logit"])))

    a = np.fromfile(work / "logits_baseline.bin", np.float32)
    b = np.fromfile(work / "logits_emulated.bin", np.float32)
    res = EmulResult(ok=True, baseline_top1=outs["baseline"][1],
                     emulated_top1=outs["emulated"][1],
                     logits_identical=a.tobytes() == b.tobytes(),
                     max_abs_logit_diff=float(np.abs(a - b).max()) if a.size == b.size else None)
    log = outs["emulated"][0]
    for spec, calls in swaps:
        sym, layer = calls[0].symbol, calls[0].layer
        entered = len(re.findall(rf"^\[aie-offload\] layer {layer:02d} .*: ENTER", log, re.M))
        failed = len(re.findall(rf"^\[aie-offload\] layer {layer:02d}: EXIT rc=(?!0,)", log, re.M))
        res.swaps[sym] = {"label": f"L{layer:02d}", "expected": len(calls),
                          "substituted": counts.get(sym, 0), "entered": entered,
                          "failed": failed}
        if entered != len(calls) or failed:
            res.ok = False
            res.reason = (f"layer {layer:02d}: {entered} ENTER / {len(calls)} calls, "
                          f"{failed} non-zero rc")
    if not res.logits_identical:
        res.ok = False
    if verbose:
        print(f"  [emul] {res.summary()}")
    return res
