"""Board-side ``main.c`` generator + the build glue around it (sprint m4 P4, gaps 3 / 4).

A model example used to carry its own ``MAIN_C`` (C text in Python), the runtime-io rewrite of it,
the inputs header and the PROF / FA declaration glue of ``graph_driver.c``. All of that is generated
here from the templates in ``src/aiegraph/runtime/`` (``board_main*.c``, ``main_*.c``, ``site_prof*.c``);
the example only names its model, its inputs and the options:

    hdr_crc = boardmain.inputs_header(out / f"{m}_inputs.h", m, inputs, defines)   # embedded inputs + #defines
    main_c  = boardmain.main_c(m, io_names, aie=True, runtime_io=True, note=(1, "timestep"))
    emod.build(main_c=main_c, runtime_io=[(name, path), ...], launch="warm", ...)

The generated main prints exactly one ``LAUNCH warm ...`` line (AIE + warm launch), one
``<model>: graph_run <ms> ms`` line, one ``in_crc32_board=X expect=Y MATCH|MISMATCH`` line and one
``CMP <model> ...`` line -- the lines the board checkers parse. The first line of every generated
main is :data:`MARKER`.
"""
from __future__ import annotations

import os
import re
import shutil
import subprocess
import zlib
from pathlib import Path

from aiednn import strip_license

MARKER = "/* generated by aiegraph */"
RUNTIME = Path(__file__).resolve().parent / "runtime"

# warm launch (kernel loaded once, later launches only reset the cores): aiehlc.sh --skip-bss +
# ZFILL_WIDE / PMLOAD_WIDE / PM_WARM_SKIP. AIEHLC_SKIP_BSS_DEFAULT=1 repeats --skip-bss for the layer
# archive, which aiegraph rebuilds with hostcompile.sh without aiehlc.sh.
WARM_DEFS = "-DAIEHLC_ZFILL_WIDE=1 -DAIEHLC_PMLOAD_WIDE=1 -DAIEHLC_PM_WARM_SKIP=1 -DAIEHLC_SKIP_BSS_DEFAULT=1"
LAUNCH_OPTS_WARM = ("skip-bss+ZFILL_WIDE+PMLOAD_WIDE+PM_WARM_SKIP,core_reset_unreset_per_launch,"
                    "bd_warm_skip=off")
LAUNCHES = ("cold", "warm")
# BSP lscript.ld reserves the heap in DDR_LOW0; kernels allocate their W/X/Y through __Runtime_Alloc
HEAP_LDFLAG = "-Wl,--defsym,_HEAP_SIZE=0x8000000"
CMP_CFLAGS = "-DP1_COS_NO_MAIN"

__all__ = ["MARKER", "WARM_DEFS", "LAUNCH_OPTS_WARM", "HEAP_LDFLAG", "CMP_CFLAGS", "launch_env", "profiling_env",
           "launch_applied", "kt_select", "main_c", "inputs_header", "append_defines", "prof_c", "driver_glue",
           "input_int32", "cross_toolchain", "read_cflags_file", "cmp_source", "ref_header"]


def _rt(name: str) -> str:
    """A runtime template's text minus its license header (so the generated main.c still starts with MARKER)."""
    with open(RUNTIME / name, encoding="utf-8", newline="") as f:
        return strip_license(f.read())


# The runtime templates name the kernel archive's host ABI after ONE default kernel prefix (kernel_prefix.txt,
# the aiednn library's own: ``aiednn_aie_stats``, ``aiednn_aie_launch_stats``, ``aiednn_prof_print``, ...) and the
# header defines (``<MODEL>_LAUNCH_WARM``), PMU helpers and CMP tag after one default model name (DEFAULT_M);
# :func:`_retarget` renames them for another model / kernel prefix.
DEFAULT_K = (RUNTIME / "kernel_prefix.txt").read_text().strip()
DEFAULT_M = "unet"


def _retarget(text: str, model: str = None, kprefix: str = None) -> str:
    """*text* (a runtime template) for *model*'s header defines / CMP tag / PMU helpers and the kernel
    archive prefix *kprefix* (default: :data:`DEFAULT_K` for the default model, else *model*; model and prefix
    default to :data:`DEFAULT_M` / :data:`DEFAULT_K`: text unchanged)."""
    d, dm = DEFAULT_K, DEFAULT_M
    m = model or dm
    k = kprefix or (d if m == dm else m)
    if m == dm and k == d:
        return text
    # site tags compared by prefix length: '"aie <k>_aie_lin ", 19' -> the new literal and its length
    text = re.sub(r'"aie %s_aie_(\w+) ", \d+' % d,
                  lambda g: '"aie %s_aie_%s ", %d' % (k, g.group(1), len("aie %s_aie_%s " % (k, g.group(1)))), text)
    text = re.sub(r"up_tag\[i\] \+ (\d+)",
                  lambda g: "up_tag[i] + %d" % (int(g.group(1)) + (len(k) - len(d)) *
                                                (int(g.group(1)) >= len(f"aie {d}_aie_"))), text)
    text = text.replace(f"{d}_aie_", f"{k}_aie_").replace(f"{d}_prof_print", f"{k}_prof_print")
    text = text.replace(f"{dm}_pmc", f"{m}_pmc").replace(f"{dm.upper()}_", f"{m.upper()}_")
    return text.replace(f'p1_cmp("{dm}"', f'p1_cmp("{m}"').replace(f'"AIE {dm}: ', f'"AIE {m}: ')


def _fill(text: str, **kv) -> str:
    for k, v in kv.items():
        text = text.replace(f"@{k}@", str(v))
    left = re.findall(r"@[A-Z][A-Z0-9_]*@", text)
    if left:
        raise ValueError(f"boardmain: unfilled template parameters {sorted(set(left))}")
    return text


def cmp_source() -> Path:
    """The board compare tool linked into every main (``p1_cmp``; build with :data:`CMP_CFLAGS`)."""
    return RUNTIME / "cmp_cos.c"


# ── launch / profiling environment (read by aiehlc.sh, hostcompile.sh and the runtime build) ──────────

def _add_defs(defs: str):
    cur = os.environ.get("EXTRA_DEFS", "")
    if defs not in cur:
        os.environ["EXTRA_DEFS"] = (cur + " " + defs).strip()


def profiling_env():
    """PH_COREEN etc. are counted only by a runtime built with -DAIEHLC_PROFILING=1."""
    os.environ["AIEHLC_PROFILING"] = "1"
    _add_defs("-DAIEHLC_PROFILING=1")


def launch_env(mode: str) -> str:
    """Set the launch options BEFORE the kernels are built (convert / offload); returns the opts string
    ``LAUNCH warm`` prints. ``cold`` = the runtime defaults."""
    if mode not in LAUNCHES:
        raise ValueError(f"launch={mode!r}: one of {LAUNCHES}")
    if mode == "cold":
        return "cold"
    # --skip-bss: the kernel's .bss is DMA port buffers / cursors written before any read
    os.environ["AIEHLC_SH_ARGS"] = "--skip-bss"
    _add_defs(WARM_DEFS)
    return LAUNCH_OPTS_WARM


def launch_applied(mode) -> bool:
    """True when the environment carries *mode*'s launch options (``emod.build(launch=...)`` checks this)."""
    if mode in (None, "cold"):
        return True
    return (WARM_DEFS in os.environ.get("EXTRA_DEFS", "")
            and "--skip-bss" in os.environ.get("AIEHLC_SH_ARGS", ""))


# ── main.c ────────────────────────────────────────────────────────────────────────────────────────────

def kt_select(text: str, ktimer: bool) -> str:
    """keep /*KT+*/../*KT-*/ spans with ktimer, /*NK+*/../*NK-*/ spans without; drop the other"""
    keep, drop = (("KT", "NK") if ktimer else ("NK", "KT"))
    text = re.sub(r"/\*%s\+\*/.*?/\*%s-\*/" % (drop, drop), "", text, flags=re.S)
    text = text.replace("/*%s+*/" % keep, "").replace("/*%s-*/" % keep, "")
    assert "/*KT" not in text and "/*NK" not in text
    return text


def main_c(model: str, io_names, *, aie: bool = False, ktimer: bool = False, runtime_io: bool = False,
           note=None, kprefix: str = None) -> str:
    """The board ``main.c`` of *model* (C identifier prefix, e.g. ``"net"`` -> ``net_inputs.h``,
    ``NET_N_INPUTS``, ``P1_NET_IN_CRC32``, ``REF_NET_OUT_N``).

    *io_names*: the input labels, in graph order (the INPUT line prints them joined with ``+``).
    *aie*: AIE build -- launch / PROF / per-phase lines and the ``CMP`` line with the launch counts
    (needs the kernel archive's ``<model>_aie_stats`` family). *runtime_io*: inputs from the
    ``.aiehlc_io`` section (``emod.build(runtime_io=...)``), the expected crc computed on the board;
    the reference compare runs only for the build's own input, the output is dumped when the
    section's dump_out flag is set. *note*: ``(k, label)`` -- input k is an int32 scalar printed as
    ``(label=%d)`` on the INPUT line. *kprefix*: the kernel archive's host ABI prefix
    (``<kprefix>_aie_stats`` ...; default: kernel_prefix.txt, the archive's own)."""
    if not re.fullmatch(r"[a-z][a-z0-9_]*", model):
        raise ValueError(f"main_c: model {model!r} must be a lower-case C identifier")
    m, mu = model, model.upper()
    nf = ne = nd = ng = nr = ""
    if note is not None:
        k, label = note
        nf = f" ({label}=%d)"
        ne = f",\n           (int){m}_{label}[0]"
        nd = "    int32_t ts = 0;\n"
        ng = f"        if (k == {int(k)}) memcpy(&ts, dst, sizeof ts);\n"
        nr = " (int)ts,"
    desc = "+".join(io_names)
    if runtime_io:
        inb = _fill(_rt("board_main_in_rtio.c"), M=m, MU=mu, IN_DESC=desc, NOTE_FMT=nf, NOTE_DECL=nd,
                    NOTE_GRAB=ng, NOTE_RARG=nr)
    else:
        inb = _fill(_rt("board_main_in_embed.c"), M=m, MU=mu, IN_DESC=desc, NOTE_FMT=nf, NOTE_EARG=ne)
    if aie:
        k = kprefix or DEFAULT_K   # kernel archive prefix: unchanged unless the caller names one
        decl = _retarget(_fill(kt_select(_rt("main_extra_decl.h"), ktimer), M=m), m, k)
        cmp_ = _retarget(_fill(kt_select(_rt("main_cmp.c"), ktimer), M=m, MU=mu), m, k)
        pre, post = _fill(_rt("board_main_pmc.c"), M=m), _fill(_rt("board_main_pmc1.c"), M=m)
        after = _retarget(_fill(_rt("main_launch_line.c"), MU=mu) + _rt("main_prof_line.c"), m, k)
        init = "aiegraph C on A78 + conv on AIE gemm_bf16"
    else:
        decl = pre = post = after = ""
        cmp_ = _fill(_rt("board_main_cmp.c"), M=m, MU=mu)
        init = "aiegraph fp32 C on A78"
    if runtime_io:
        calls = re.findall(r"^    int rc = p1_cmp\([^;]*\);\n", cmp_, re.M)
        if len(calls) != 1:
            raise ValueError(f"main_c: compare block has {len(calls)} p1_cmp calls (need 1)")
        call = calls[0]
        launches, runrc = ("launches", "run_rc") if aie else ("0", "0")
        cmp_ = cmp_.replace(call, _fill(_rt("board_main_cmp_rtio.c"), M=m, CALL=call.strip().replace(
            "int rc = ", "rc = "), LAUNCHES=launches, RUNRC=runrc), 1)
    return _fill(_rt("board_main.c"), M=m, MU=mu, IO_NOTE=", .aiehlc_io section" if runtime_io else "",
                 IO_INCLUDE='#include "aiehlc_io.h"\n' if runtime_io else "", EXTRA_DECL=decl, INIT_DESC=init,
                 INPUT_BLOCK=inb, RUN_PRE=pre, RUN_POST=post, AFTER_RUN=after, CMP=cmp_)


def _c_array(ctype, name, vals, fmt):
    body = ",\n".join(", ".join(fmt(v) for v in vals[i:i + 8]) for i in range(0, len(vals), 8))
    return f"static const {ctype} {name}[{len(vals)}] __attribute__((aligned(64))) = {{\n{body}\n}};\n"


def inputs_header(path, model: str, inputs, defines=None, origin: str = "") -> str:
    """``<model>_inputs.h``: every graph input as an embedded array + ``<MODEL>_<name>`` defines.
    *inputs*: ``[(graph name, c name, numpy array)]`` in graph order (float32 / int32 arrays).
    *defines*: ``{NAME: value}`` -> ``#define <MODEL>_NAME value`` (str values are quoted).
    Returns the crc32 of the inputs' bytes concatenated (what the board prints as in_crc32_board)."""
    import numpy as np
    m, mu = model, model.upper()
    hx = lambda v: "%.9ef" % float(v)
    txt = [f"/* generated by aiegraph.boardmain{' from ' + str(origin) if origin else ''} -- do not edit */",
           "#pragma once", "#include <stdint.h>"]
    txt += _define_lines(mu, defines or {})
    txt.append(f"#define {mu}_N_INPUTS {len(inputs)}")
    crc = 0
    for _, cn, arr in inputs:
        if arr.dtype == np.float32:
            txt.append(_c_array("float", f"{m}_{cn}", arr, hx))
        elif arr.dtype == np.int32:
            txt.append(_c_array("int32_t", f"{m}_{cn}", arr, lambda v: "%d" % int(v)))
        else:
            raise ValueError(f"inputs_header: {cn} dtype {arr.dtype} (float32 / int32 only)")
        crc = zlib.crc32(arr.tobytes(), crc)
    n = len(inputs)
    txt += ["static const char *const %s_in_name[%d] = {%s};" % (m, n, ", ".join(f'"{g}"' for g, _, _ in inputs)),
            "static const void *const %s_in_ptr[%d] = {%s};" % (m, n, ", ".join(f"{m}_{c}" for _, c, _ in inputs)),
            "static const unsigned long %s_in_bytes[%d] = {%s};" % (m, n, ", ".join(str(a.nbytes)
                                                                                for _, _, a in inputs)), ""]
    Path(path).write_text("\n".join(txt))
    return "%08x" % crc


def _define_lines(mu: str, defines: dict) -> list:
    out = []
    for k, v in defines.items():
        out.append(f'#define {mu}_{k} "{v}"' if isinstance(v, str) else f"#define {mu}_{k} {v}")
    return out


def append_defines(path, model: str, defines: dict):
    """Append ``#define <MODEL>_NAME value`` lines to a generated header (str values are quoted;
    :class:`int` values plain; ``(value, "ULL")`` adds a suffix)."""
    lines = []
    for k, v in defines.items():
        if isinstance(v, tuple):
            lines.append(f"#define {model.upper()}_{k} {v[0]}{v[1]}")
        else:
            lines += _define_lines(model.upper(), {k: v})
    with open(path, "a") as f:
        f.write("\n".join(lines) + "\n")


def ref_header(path, model: str, ref, in_crc: str, data: str) -> Path:
    """``p1_ref.h`` for :func:`cmp_source` (``p1_cmp``) and the generated main: the reference output
    *ref* (float32, the board's whole output) of the build's own input (crc32 *in_crc*), *data* the label
    the CMP line prints. Defines ``REF_<MODEL>_OUT_N``, ``P1_<MODEL>_IN_CRC32`` and the generic
    ``P1_REF_OUT`` / ``P1_REF_OUT_N`` / ``P1_REF_IN_CRC32`` cmp_cos.c compares with."""
    import numpy as np
    if not re.fullmatch(r"[a-z][a-z0-9_]*", model):
        raise ValueError(f"ref_header: model {model!r} must be a lower-case C identifier")
    if not re.fullmatch(r"[0-9a-f]{8}", in_crc):
        raise ValueError(f"ref_header: in_crc {in_crc!r} is not a crc32 hex string")
    data = data.replace('"', "'")
    m, mu = model, model.upper()
    a = np.ascontiguousarray(ref, dtype=np.float32).reshape(-1)
    txt = [f"/* generated by aiegraph.boardmain.ref_header -- do not edit */", "#pragma once",
           f'#define P1_DATA "{data}"', f'#define P1_{mu}_IN_CRC32 "{in_crc}"', f"#define REF_{mu}_OUT_N {a.size}",
           f"#define P1_REF_OUT ref_{m}_out", f"#define P1_REF_OUT_N REF_{mu}_OUT_N",
           f"#define P1_REF_IN_CRC32 P1_{mu}_IN_CRC32",
           _c_array("float", f"ref_{m}_out", a, lambda v: "%.9ef" % float(v))]
    Path(path).write_text("\n".join(txt))
    return Path(path)


# ── graph_driver.c glue (emod.driver_template) ───────────────────────────────────────────────────────

EXPAND_ENTER = "    XTime e0_, e1_;\n    XTime_GetTime(&e0_);\n"
EXPAND_EXIT = "    XTime_GetTime(&e1_);\n    up_pending_exp += e1_ - e0_;\n    up_exp_calls++;\n"
RUN_ENTER = "    up_pending_exp = 0; /* P1 PROF: expands before graph_run are not graph_run time */\n"
_PROF_BRANCH_AT = "        if (is_aie && strncmp("


def prof_c(attn: bool = False, kprefix: str = None) -> str:
    """Per-call-site A78 time (PROF lines) placed in graph_driver.c; *attn*: attention sites print
    ``op=aie_host_attn<cid>``; *kprefix*: the kernel archive's host ABI prefix (see :func:`main_c`)."""
    t = _retarget(_rt("site_prof.c"), kprefix, kprefix)
    if not attn:
        return t
    if t.count(_PROF_BRANCH_AT) != 1:
        raise ValueError("prof_c: site_prof.c branch anchor not found once")
    return t.replace(_PROF_BRANCH_AT, _retarget(_rt("site_prof_attn_branch.c"), kprefix, kprefix) +
                     _PROF_BRANCH_AT.lstrip(), 1)


def driver_glue(decls: str = "", attn: bool = False, kprefix: str = None, bf16_expand: bool = True) -> dict:
    """``emod.driver_template(**driver_glue(...))``: *decls* (kernel declarations of the group steps
    that are not aiegraph-generated, e.g. fused attention) + the PROF glue + expand timing
    (*bf16_expand*: the driver has ``graph_bf16_expand``, i.e. ``AIEGRAPH_WDTYPE=bf16``)."""
    ee, ex = (EXPAND_ENTER, EXPAND_EXIT) if bf16_expand else ("", "")
    return dict(decls=decls + prof_c(attn, kprefix) + "\n", expand_enter=ee, expand_exit=ex,
                run_enter=RUN_ENTER)


# ── model / toolchain helpers ─────────────────────────────────────────────────────────────────────────

_I32_VERSION = 1            # bump when input_int32's rewrite changes (part of the F12 cache key)
I32_CACHE_ENV = "AIEHLC_I32_CACHE"


def _i32_cache_dir():
    """F12: content cache for input_int32. AIEHLC_I32_CACHE=<dir>, or under AIEHLC_FAST=1
    ${XDG_CACHE_HOME:-~/.cache}/aiehlc/i32; AIEHLC_I32_CACHE=0 disables."""
    d = os.environ.get(I32_CACHE_ENV, "").strip()
    if d == "0":
        return None
    if not d and os.environ.get("AIEHLC_FAST", "0").strip() == "1":
        xdg = os.environ.get("XDG_CACHE_HOME", "").strip() or str(Path.home() / ".cache")
        d = str(Path(xdg) / "aiehlc" / "i32")
    return Path(d).resolve() if d else None


def _i32_key(src: Path, name: str) -> str:
    import hashlib
    import onnx
    h = hashlib.sha1(f"v{_I32_VERSION}\0{name}\0onnx {onnx.__version__}\0".encode())
    with open(src, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 22), b""):
            h.update(chunk)
    return h.hexdigest()


def _i32_place(ent: Path, dst: Path) -> str:
    """Put cache entry *ent* at *dst*: hardlink (entry is 0444) or copy on EXDEV/EPERM."""
    tmp = dst.with_suffix(".tmp.onnx")
    tmp.unlink(missing_ok=True)
    try:
        os.link(ent, tmp)
        how = "link"
    except OSError:
        shutil.copyfile(ent, tmp)
        how = "copy"
    tmp.replace(dst)
    return how


def input_int32(src, dst, name: str, log=print) -> Path:
    """Rewrite graph input *name* int64 -> int32 + Cast(to int64) feeding the old consumers, so the board
    runtime receives exactly the 4-byte value. Reuses *dst* when newer than *src*; with a cache dir
    (AIEHLC_FAST / AIEHLC_I32_CACHE) the result is also reused across --out dirs by the sha1 of *src*."""
    src, dst = Path(src), Path(dst)
    if dst.is_file() and dst.stat().st_mtime > src.stat().st_mtime:
        log(f"reuse {dst}")
        return dst
    cdir, ent = _i32_cache_dir(), None
    if cdir is not None:
        ent = cdir / f"{_i32_key(src, name)}.onnx"
        if ent.is_file():
            how = _i32_place(ent, dst)
            os.utime(ent)                              # LRU-ish: newest use
            log(f"{name} int64 -> int32: cache hit {ent.name[:12]} ({how}) -> {dst}")
            return dst
    _input_int32_rewrite(src, dst, name)
    log(f"{name} int64 -> int32 input + Cast: {dst} ({dst.stat().st_size:,} B)")
    if ent is not None:
        try:
            cdir.mkdir(parents=True, exist_ok=True)
            tmp = ent.with_suffix(f".{os.getpid()}.tmp")
            tmp.unlink(missing_ok=True)
            try:
                os.link(dst, tmp)                      # same fs: dst and the entry share one inode
                linked = True
            except OSError:                            # EXDEV -> a copy, then dst points at it too
                shutil.copyfile(dst, tmp)
                linked = False
            os.chmod(tmp, 0o444)                       # shared inode: writers must fail loudly
            tmp.replace(ent)
            if not linked:
                _i32_place(ent, dst)
            for old in sorted(cdir.glob("*.onnx"), key=lambda p: p.stat().st_mtime)[:-2]:
                old.unlink(missing_ok=True)            # keep the 2 newest entries (each ~model size)
        except OSError as e:
            log(f"i32 cache store failed: {e}")
    return dst


def _input_int32_rewrite(src: Path, dst: Path, name: str):
    import onnx
    from onnx import TensorProto, helper
    m = onnx.load(str(src))
    inp = next(i for i in m.graph.input if i.name == name)
    assert inp.type.tensor_type.elem_type == TensorProto.INT64, inp
    inp.type.tensor_type.elem_type = TensorProto.INT32
    for n in m.graph.node:
        n.input[:] = [f"{name}_i64" if x == name else x for x in n.input]
    m.graph.node.insert(0, helper.make_node("Cast", [name], [f"{name}_i64"], to=TensorProto.INT64,
                                            name=f"{name}_i32_to_i64"))
    onnx.checker.check_model(m) if m.ByteSize() < 2**31 - 1 else None
    tmp = dst.with_suffix(".tmp.onnx")
    onnx.save(m, str(tmp))
    tmp.replace(dst)


def cross_toolchain(root, log=print):
    """Put aarch64-none-elf-gcc on PATH from ``<root>/script/setup.sh`` when it is not there yet."""
    if shutil.which("aarch64-none-elf-gcc"):
        return
    env = subprocess.run(["bash", "-c", f"cd {root} && source script/setup.sh --path-set-only >/dev/null 2>&1; env -0"],
                         capture_output=True, check=True).stdout.decode()
    os.environ.update(kv.split("=", 1) for kv in env.split("\0") if "=" in kv)
    log(f"toolchain via {root}/script/setup.sh: {shutil.which('aarch64-none-elf-gcc')}")


def read_cflags_file(path) -> str:
    """A cflags file's lines joined with single spaces (one string, no shell word-splitting).
    Lines starting with `#` are comments (e.g. the license header) and are skipped.
    A missing or empty (whitespace/comment-only) file is an error, never a silent ''."""
    path = Path(path)
    if not path.is_file():
        raise ValueError(f"{path}: no such cflags file")
    lines = [ln for ln in path.read_text().splitlines() if not ln.lstrip().startswith("#")]
    flags = " ".join(" ".join(lines).split())
    if not flags:
        raise ValueError(f"{path}: cflags file is empty")
    return flags
