"""The prebuilt aiednn library: build once, link any app at compile time.

``build_library(target="vek280")`` builds the aiednn runtime, its implementation list and the fixed
megakernel set (``dnn.LIBRARY_MEGAKERNELS``: cnn / act / attn / float, each a prebuilt kernel ELF
embedded in the archive) into ONE static library, and lays out a self-contained distribution:

    <dist>/include/aiednn.h           the API (create = the query: dispatch picks the implementation,
                                      aiednn_primitive_impl_candidates lists every one that can serve)
    <dist>/lib/libaiednn.a            runtime + impl list + kernel ELFs + AIE runtime + routing
    <dist>/lib/libxaiengine*.a        aie-rt (a copy: aiehlc.sh wipes its own on every run)
    <dist>/lib/bsp/                   the board support libraries the final link needs
    <dist>/lib/lscript.ld             the board's linker script
    <dist>/link.mk                    AIEDNN_CXX / AIEDNN_CXXFLAGS / AIEDNN_LDFLAGS / AIEDNN_LIBS

An app is then plain C/C++ against ``aiednn.h`` -- no aiehlc, no kernel source, no per-app build of
the AIE side::

    include <dist>/link.mk
    app.elf: app.o
            $(AIEDNN_CXX) -o $@ app.o $(AIEDNN_LDFLAGS) $(AIEDNN_LIBS)

How it is built: ``dnn_build(modes="library")`` on an entry WITHOUT ``main()`` -- aiehlc then archives
instead of linking (hostlibrarymode) -- with every kernel of the board; the link line hostcompile.sh
prints for such an archive names exactly the libraries and script the distribution copies.

``mode="eager"`` builds the same distribution from EAGER mode instead: the premade template library
(``dnn_eager.library_plan``: every eager template, 74 shape-specialized instances, each its own kernel
ELF + routing) compiled once for one mesh (``eager_rows`` x 4). The app side is identical -- plain C/C++
against ``aiednn.h``; creating a primitive picks among the linked ``eager:*`` implementations
(``aiednn_primitive_find`` / ``aiednn_primitive_set_impl`` as for any implementation), each launch loads
its instance. The per-app eager build (``dnn_build(mode="eager")``, instances made for one model) stays.
"""
from __future__ import annotations

import re
import shutil
from dataclasses import dataclass, field
from pathlib import Path
from typing import Optional

from . import _env
from .errors import AiegraphError

#: the stub "app": no main() (=> an archive), every primitive family named so dnn_build picks the GEMM
#: source and all its entries; never called
_STUB = """// Generated by aiegraph/dnn_lib.py: the prebuilt aiednn library's build entry. No main(): aiehlc
// archives the runtime, the implementation list and the kernel ELFs instead of linking an app.
#include "aiednn.h"
extern "C" int aiednn_library_families(void) {
    /* the families the library serves (dnn_build reads them from the text; this is never called) */
    aiednn_primitive_t p = nullptr;
    (void)aiednn_matmul_forward_create(&p, nullptr, nullptr, nullptr, nullptr, 0);
    (void)aiednn_convolution_forward_create(&p, nullptr, nullptr, nullptr, nullptr, nullptr);
    return 0;
}
"""


@dataclass
class LibraryBuild:
    target: str
    dist: Path
    ok: bool = False
    reason: str = ""
    archive: Optional[Path] = None
    files: list = field(default_factory=list)
    log: Optional[Path] = None


_LINK = re.compile(r"g\+\+ .*?-o app main\.o\s*\\\s*\n(?P<body>(?:\s+.*\\\n)*\s+.*--end-group)", re.M)


def _link_line(log_text: str) -> dict:
    """the pieces of hostcompile.sh's printed link line for a library build"""
    m = _LINK.search(log_text)
    if not m:
        raise AiegraphError("dnn_lib", "no link line in the build log (did aiehlc archive a library?)")
    body = m.group("body").replace("\\\n", " ")
    ls, grp = re.search(r"-Wl,-T -Wl,(\S+)", body), re.search(r"--start-group,(\S+?),--end-group", body)
    if not ls or not grp:
        raise AiegraphError("dnn_lib", "the build log's link line has no linker script / library group")
    return dict(lscript=ls.group(1), libdirs=[d.strip('"') for d in re.findall(r'-L"?([^"\s]+)"?', body)],
                group=grp.group(1).split(","))


def _find_lib(name: str, dirs) -> Optional[Path]:
    for d in dirs:
        p = Path(d) / f"lib{name}.a"
        if p.is_file():
            return p
    return None


def build_library(target: str = "vek280", dist=None, mesh=None, vitis_settings=None, verbose: bool = False,
                  mode: str = "fixed-megakernel", eager_rows: int = 4) -> LibraryBuild:
    """Build the prebuilt aiednn library for *target* into *dist* (default worklocal/aiednn/lib_<target>, eager:
    lib_<target>_eager_<rows>x4). *mode* "eager": the premade eager template library for an *eager_rows* x 4 mesh
    instead of the fixed megakernel set."""
    from .dnn import BUILD_MODES, TARGETS, dnn_build
    if target not in TARGETS or target == "x86":
        raise AiegraphError("dnn_lib", f"target={target!r}", hint="a board target, e.g. vek280")
    if mode not in BUILD_MODES:
        raise AiegraphError("dnn_lib", f"mode={mode!r}", hint=f"one of {', '.join(BUILD_MODES)}")
    eager = mode == "eager"
    tag = f"_eager_{eager_rows}x4" if eager else ""
    repo = _env.repo_root()
    work = repo / "worklocal" / "aiednn" / f"libbuild_{target}{tag}"
    work.mkdir(parents=True, exist_ok=True)
    stub = work / "aiednn_library.cc"
    stub.write_text(_STUB)
    dist = Path(dist or repo / "worklocal" / "aiednn" / f"lib_{target}{tag}").resolve()
    out = LibraryBuild(target, dist)
    if eager:   # every eager template: the runtime picks among the linked instances at create
        from . import dnn_eager
        rep = dnn_build(stub, target=target, out=work / target, mode="eager",
                        eager=dnn_eager.library_plan("aiednn_library", eager_rows),
                        vitis_settings=vitis_settings, verbose=verbose)
    else:
        rep = dnn_build(stub, target=target, out=work / target, modes="library", mesh=mesh,
                        vitis_settings=vitis_settings, verbose=verbose)
    out.log = rep.log
    arch = work / target / "aout" / f"lib{stub.stem}_aiednn.a"
    if not rep.ok or not arch.is_file():   # rep.ok: the program-memory / stack checks of every ELF passed
        out.reason = rep.reason or f"no {arch.name}; see {rep.log}"
        return out
    link = _link_line(Path(rep.log).read_text(errors="replace"))
    if dist.exists():
        shutil.rmtree(dist)
    (dist / "include").mkdir(parents=True)
    (dist / "lib" / "bsp").mkdir(parents=True)
    shutil.copy2(repo / "include" / "aiednn.h", dist / "include" / "aiednn.h")
    shutil.copy2(arch, dist / "lib" / "libaiednn.a")
    shutil.copy2(link["lscript"], dist / "lib" / "lscript.ld")
    libs = []
    for name in (g[2:] for g in link["group"] if g.startswith("-l")):
        src = _find_lib(name, link["libdirs"])
        if src is None:           # libc / libm / libgcc / libstdc++: the toolchain's own
            libs.append(f"-l{name}")
            continue
        dst = dist / "lib" / ("bsp" if "aiengine" not in name else "") / src.name
        shutil.copy2(src, dst)
        libs.append(f"-l{name}")
    for d in link["libdirs"]:     # the BSP's other archives a group member may pull (xilpm, ...)
        for a in Path(d).glob("libxil*.a"):
            if not (dist / "lib" / "bsp" / a.name).exists() and "aiengine" not in a.name:
                shutil.copy2(a, dist / "lib" / "bsp" / a.name)
    group = ",".join(libs)
    (dist / "link.mk").write_text(f"""# Generated by aiegraph/dnn_lib.py: link an app against the prebuilt aiednn library ({target}, {
        f"eager mode, {eager_rows}x4 mesh" if eager else "fixed-megakernel mode"}).
AIEDNN_DIST     := {dist}
AIEDNN_CXX      := aarch64-none-elf-g++
AIEDNN_CXXFLAGS := -O2 -I$(AIEDNN_DIST)/include
# heap: 512 MB (the BSP script's default is 128 MB; large f32 composites outgrow it)
AIEDNN_HEAP     ?= 0x20000000
AIEDNN_LDFLAGS  := --specs=nosys.specs -Wl,--defsym,end=__bss_end__ -Wl,--defsym,_HEAP_SIZE=$(AIEDNN_HEAP) \\
                   -Wl,-T -Wl,$(AIEDNN_DIST)/lib/lscript.ld \\
                   -L$(AIEDNN_DIST)/lib -L$(AIEDNN_DIST)/lib/bsp
# whole archive: the runtime reaches routing() and the embedded kernel ELFs through WEAK references,
# which do not pull archive members -- without it the app links and then finds no routing on the board
AIEDNN_LIBS     := -Wl,--whole-archive $(AIEDNN_DIST)/lib/libaiednn.a -Wl,--no-whole-archive \\
                   -Wl,--start-group,{group},--end-group
""")
    out.files = sorted(str(p.relative_to(dist)) for p in dist.rglob("*") if p.is_file())
    out.archive, out.ok = dist / "lib" / "libaiednn.a", True
    return out
