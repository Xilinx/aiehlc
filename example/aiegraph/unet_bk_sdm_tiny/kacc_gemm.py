#!/usr/bin/env python3
"""PDK: kacc_bench.sh --gemm -- the K-in-core gemm_kacc kernel (unet_aie.kacc_kernel_text) as a dense GEMM.

  kacc_gemm.py <op_golden matmul dir> <out dir>   -> <out>/kacc_gemm.cc + kacc_{w,x,y}.bin + kacc_data.h

Golden dir: a.npy [1, M, K] f32, b.npy [K, N] f32, y.npy [1, M, N] f32, meta.json (op_golden p0 MatMul).
Mapping onto gemm_kacc(ch, k, px) (Y[ch][px] = W[ch, :] . X[px, :], see unet_aie.kacc_geom):
  ch = N (out features, W = b^T [N][K]), px = M padded to a multiple of 64 (zero rows, not compared), k = K.
If one instance does not fit the core (kacc_geom asserts: the fp32 accumulator window is too big), the GEMM is
split into S launches of one instance, along px first (X rows contiguous), then along ch (W rows contiguous).
Host side (main): one warm-up pass of all launches (kernel load + first-launch config), then the timed pass;
[BENCH] aie_wall_ms is the timed pass. Numerics: bf16 operands, fp32 accumulation over all of K in the core,
no bias; KCMP cos is against the fp32 golden y.npy.
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import unet_aie as ua  # noqa: E402


def bf16(a):  # round to nearest even
    u = np.ascontiguousarray(a, np.float32).view(np.uint32).astype(np.uint64)
    return ((u + 0x7fff + ((u >> 16) & 1)) >> 16).astype(np.uint16)


def fits(ch, k, px):
    try:
        ua.kacc_geom(ch, k, px)
        return True
    except AssertionError:
        return False


def plan(N, K, Mp):
    if fits(N, K, Mp):
        return "none", 1, N, Mp
    for s in (2, 4, 8, 16):
        if Mp % (64 * s) == 0 and fits(N, K, Mp // s):
            return "px", s, N, Mp // s
    for s in (2, 4, 8, 16):
        if N % (64 * s) == 0 and fits(N // s, K, Mp):
            return "ch", s, N // s, Mp
    raise SystemExit(f"[kacc_gemm] no split of N={N} K={K} M={Mp} fits gemm_kacc")


def layout(rows_bf16, kp, kch, wside):
    """natural [R][kp] bf16 -> kacc chunk layout: 16-row block, chunk j at j*kch of each row, in-chunk flat
    f = hi*8*kch + kb*64 + (W: mm*8 + kk | X: kk*8 + nn)  (unet_aie.kacc_wlayout / uc_conv im2col table)"""
    R = rows_bf16.shape[0]
    t = rows_bf16.reshape(R // 16, 2, 8, kp // kch, kch // 8, 8)       # blk hi lo j kb kk
    t = t.transpose(0, 3, 1, 4, 2, 5) if wside else t.transpose(0, 3, 1, 4, 5, 2)
    t = t.reshape(R // 16, kp // kch, 16, kch).transpose(0, 2, 1, 3)  # blk row j q
    return np.ascontiguousarray(t).reshape(R, kp)


def main():
    g, out = Path(sys.argv[1]), Path(sys.argv[2])
    meta = json.load(open(g / "meta.json"))
    assert meta["op"] == "MatMul", meta["op"]
    a = np.load(g / "a.npy").astype(np.float32)
    b = np.load(g / "b.npy").astype(np.float32)
    y = np.load(g / "y.npy")
    assert y.dtype == np.float32, y.dtype
    ysha = hashlib.sha256(y.tobytes()).hexdigest()[:12]
    assert meta["y_sha256"].startswith(ysha), (ysha, meta["y_sha256"])
    assert a.ndim == 3 and a.shape[0] == 1 and b.ndim == 2 and a.shape[2] == b.shape[0], (a.shape, b.shape)
    M, K = a.shape[1:]
    N = b.shape[1]
    Mp = -(-M // 64) * 64
    mode, S, chs, pxs = plan(N, K, Mp)
    geo = ua.kacc_geom(chs, K, pxs)
    kch, kp, tr = geo["kch"], geo["kp"], geo["tr"]
    X = np.zeros((Mp, kp), np.float32)
    X[:M, :K] = a[0]
    W = np.zeros((N, kp), np.float32)
    W[:, :K] = b.T
    Xb, Wb = bf16(X), bf16(W)
    f = lambda u: (u.astype(np.uint32) << 16).view(np.float32).astype(np.float64)
    ref = f(Xb[:M]) @ f(Wb).T
    yr = y.reshape(M, N).astype(np.float64)
    cos = (ref * yr).sum() / np.sqrt((ref * ref).sum() * (yr * yr).sum())
    gmac = M * N * K / 1e9
    print(f"[kacc_gemm] M={M} Mp={Mp} K={K} N={N} split={mode} S={S} instance=(ch {chs}, k {K}, px {pxs}) "
          f"kch={kch} kp={kp} tr={tr} ntile={geo['ntile']} sub={geo['S']} nkc={geo['nkc']} l1={geo['l1']} "
          f"gmac={gmac:.4f} bf16-gemm vs golden cos={cos:.6f} y_sha256={ysha}")
    layout(Wb, kp, kch, True).astype("<u2").tofile(out / "kacc_w.bin")
    layout(Xb, kp, kch, False).astype("<u2").tofile(out / "kacc_x.bin")
    y.astype("<f4").reshape(-1).tofile(out / "kacc_y.bin")
    data = "op_golden/" + "/".join(str(g).rstrip("/").split("/")[-2:])
    data = data[:data.rindex("/") + 5]  # op_golden/<set>/cNNN
    tag = data.split("/")[-1] + "-kacc-gemm"
    inc = lambda n: f'    ".balign 64\\n.global {n}\\n{n}:\\n.incbin \\"{out}/{n[:-4]}.bin\\"\\n"\n'
    (out / "kacc_data.h").write_text(f"""/* generated by kacc_gemm.py (kacc_bench.sh --gemm) from {g} */
#ifndef KACC_DATA_H
#define KACC_DATA_H
#include "unistd.h"
#include "xil_cache.h"
#include "xiltimer.h"
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define KACC_M {M}
#define KACC_MP {Mp}
#define KACC_K {K}
#define KACC_KP {kp}
#define KACC_N {N}
#define KACC_S {S}
#define KACC_SPLIT_PX {int(mode == "px")}
#define KACC_CHS {chs}
#define KACC_PXS {pxs}
#define KACC_TR {tr}
#define KACC_GMAC {gmac:.6f}
#define KACC_DATA "{data}"
#define KACC_TAG "{tag}"
#define KACC_Y_SHA "{ysha}"
#if defined(__aarch64__)
__asm__(".section .rodata.kacc,\\"a\\"\\n"
{inc("kacc_w_bin")}{inc("kacc_x_bin")}{inc("kacc_y_bin")}    ".previous\\n");
extern "C" const uint8_t kacc_w_bin[], kacc_x_bin[], kacc_y_bin[];
#else
static const uint8_t kacc_w_bin[64] = {{0}}, kacc_x_bin[64] = {{0}}, kacc_y_bin[64] = {{0}};
#endif
#endif
""")
    name = ua.kacc_name(chs, K, pxs)
    args = "Xs, Ws, Ys" if tr else "Ws, Xs, Ys"
    src = (ua.CTRLPKT_PRAGMAS + "// kacc_gemm.cc -- generated by kacc_gemm.py: gemm_kacc as a dense GEMM (PDK probe)\n"
           "#define UNET_KACC_KERNEL 1\n#include \"kacc_data.h\"\n\n" + ua.kacc_kernel_text(chs, K, pxs) + "\n" +
           HOST.replace("@NAME@", name).replace("@ARGS@", args))
    (out / "kacc_gemm.cc").write_text(src)
    print(f"[kacc_bench] data={data} tag={tag} kernel={name} launches_per_pass={S}")


HOST = r"""
void __Runtime_ctrl_high_throughput_enable(int on); /* C++ linkage, as aie_runtime.h:936 */

/* device index of Y[m][n] in launch s's fp32 c buffer (unet_aie uc_conv un-tiling, P4bx [s][mi][ni][8x8]) */
static size_t kacc_yidx(int m, int n) {
    const int s = KACC_SPLIT_PX ? m / KACC_PXS : n / KACC_CHS;
    const int ml = KACC_SPLIT_PX ? m % KACC_PXS : m, nl = KACC_SPLIT_PX ? n : n % KACC_CHS;
    const int Ml = KACC_PXS, Nl = KACC_CHS, r = nl & 15, c = ml & 15;
    size_t base = (size_t)s * Ml * Nl, i;
    if (!KACC_TR) {
        const int q = Ml / 4, cc = ml % q;
        const int wi = (cc >> 4) * 256 + ((r >> 3) * 2 + (c >> 3)) * 64 + (r & 7) * 8 + (c & 7);
        i = (size_t)((nl & ~15) + wi / q) * Ml + (ml - cc) + wi % q;
    } else {
        const int q = Nl / 4, cc = nl % q;
        const int wi = (cc >> 4) * 256 + ((r >> 3) * 2 + (c >> 3)) * 64 + (r & 7) * 8 + (c & 7);
        i = (size_t)((ml & ~15) + wi / q) * Nl + (nl - cc) + wi % q;
    }
    return base + i;
}

int main() {
    printf("=== PDK gemm_kacc dense GEMM M=%d (pad %d) K=%d N=%d: %d launch(es) of @NAME@ per pass, 4x4 mesh ===\n",
           KACC_M, KACC_MP, KACC_K, KACC_N, KACC_S);
    __Runtime_ctrl_high_throughput_enable(1);
    aieSetDevice(0);
    aieArray device;
    aieMesh mesh = device.partition({2, 6, 0, 6}, 4, 4);
    const size_t wbytes = (size_t)KACC_N * KACC_KP * 2, xbytes = (size_t)KACC_MP * KACC_KP * 2;
    const size_t ybytes = (size_t)KACC_N * KACC_MP * 4;
    int32_t *Wd = (int32_t *)__Runtime_Alloc(wbytes);
    int32_t *Xd = (int32_t *)__Runtime_Alloc(xbytes);
    int32_t *Yd = (int32_t *)__Runtime_Alloc(ybytes);
    if (!Wd || !Xd || !Yd) {
        printf("KCMP %s data=%s y_sha256=%s cos=0.000000 FAIL (alloc)\n", KACC_TAG, KACC_DATA, KACC_Y_SHA);
        return 1;
    }
    memcpy(Wd, kacc_w_bin, wbytes);
    memcpy(Xd, kacc_x_bin, xbytes);
    Xil_DCacheFlushRange((UINTPTR)Wd, wbytes);
    Xil_DCacheFlushRange((UINTPTR)Xd, xbytes);
    double wall[2] = {0, 0};
    int launches = 0;
    for (int pass = 0; pass < 2; pass++) { /* pass 0: warm-up (kernel load), pass 1: timed */
        memset(Yd, 0xff, ybytes);          /* sentinel: an element the timed pass does not write is nonfinite */
        Xil_DCacheFlushRange((UINTPTR)Yd, ybytes);
        XTime t0, t1;
        XTime_GetTime(&t0);
        for (int s = 0; s < KACC_S; s++) {
            int32_t *Ws = Wd + (KACC_SPLIT_PX ? 0 : (size_t)s * KACC_CHS * KACC_KP / 2);
            int32_t *Xs = Xd + (KACC_SPLIT_PX ? (size_t)s * KACC_PXS * KACC_KP / 2 : 0);
            int32_t *Ys = Yd + (size_t)s * KACC_CHS * KACC_PXS;
            @NAME@<<<mesh>>>(@ARGS@);
            if (pass)
                launches++;
        }
        XTime_GetTime(&t1);
        wall[pass] = 1.0 * (t1 - t0) / COUNTS_PER_SECOND * 1000.0;
        Xil_DCacheInvalidateRange((UINTPTR)Yd, ybytes);
    }
    printf("[BENCH] aie_wall_ms=%.3f launches=%d warmup_wall_ms=%.3f warmup_launches=%d gmac=%.4f ms_per_gmac=%.2f\n",
           wall[1], launches, wall[0], KACC_S, KACC_GMAC, wall[1] / KACC_GMAC);
    const float *ref = (const float *)kacc_y_bin; /* [M][N] */
    double dot = 0, na = 0, nr = 0, maxabs = 0;
    int nonfinite = 0;
    for (int m = 0; m < KACC_M; m++)
        for (int n = 0; n < KACC_N; n++) {
            float f;
            memcpy(&f, &Yd[kacc_yidx(m, n)], 4);
            const double o = (double)f, r = ref[(size_t)m * KACC_N + n];
            if (!(o == o) || o > 1e30 || o < -1e30) {
                nonfinite++;
                continue;
            }
            dot += o * r;
            na += o * o;
            nr += r * r;
            if (fabs(o - r) > maxabs)
                maxabs = fabs(o - r);
        }
    const double cs = nonfinite ? 0.0 : dot / (sqrt(na) * sqrt(nr) + 1e-30);
    const int pass = nonfinite == 0 && cs >= 0.9995;
    printf("[PDK] maxabs_vs_ref=%.6g nonfinite=%d M=%d N=%d K=%d\n", maxabs, nonfinite, KACC_M, KACC_N, KACC_K);
    printf("KCMP %s data=%s y_sha256=%s cos=%.6f %s\n", KACC_TAG, KACC_DATA, KACC_Y_SHA, cs, pass ? "PASS" : "FAIL");
    return pass ? 0 : 1;
}
"""

if __name__ == "__main__":
    main()
