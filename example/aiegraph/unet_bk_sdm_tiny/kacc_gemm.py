def main_bmm(g, out):
    """PBK: attention bmm (a.npy [1,H,M,K], b.npy [1,H,K,N]) -- B and A packed by the HOST at run time
    (src/mlir/runtime/aie_kacc_pack.h), M/K/N zero-padded to 64 (aiegraph.gemmpad.pad_mkn), H heads x S launches
    of one gemm_kacc instance; numerics bf16 in, fp32 acc over all of K, one bf16 RNE SRS on the output."""
    sys.path.insert(0, str(HERE.parents[2] / "src"))
    from aiegraph.gemmpad import pad_mkn
    meta = json.load(open(g / "meta.json"))
    assert meta["op"] == "MatMul", meta["op"]
    a = np.load(g / "a.npy").astype(np.float32)
    b = np.load(g / "b.npy").astype(np.float32)
    y = np.load(g / "y.npy")
    assert y.dtype == np.float32, y.dtype
    ysha = hashlib.sha256(y.tobytes()).hexdigest()[:12]
    assert meta["y_sha256"].startswith(ysha), (ysha, meta["y_sha256"])
    assert a.ndim == 4 and b.ndim == 4 and a.shape[:2] == b.shape[:2] == (1, a.shape[1]) and a.shape[3] == b.shape[2]
    H, M, K = a.shape[1:]
    N = b.shape[3]
    Mp, Kp, Np = pad_mkn(M, K, N)
    mode, S, chs, pxs = plan(Np, Kp, Mp)
    geo = ua.kacc_geom(chs, Kp, pxs)
    # GAP (PBK, c013 256x80x256): when the a and b ports have the same shape (ch == px, both <rows, kp/2>) aiehlc's
    # GemmSpace derivation sizes the b ping/pong window as the a block (1 KiB instead of {px/4, tkw} = 4 KiB) and
    # the kernel link fails ("cannot find free area ... buf_in_ping_1"). Workaround: one more zero 64-row N block.
    while geo["arows"] == geo["brows"] and mode == "none":
        Np += 64
        mode, S, chs, pxs = plan(Np, Kp, Mp)
        geo = ua.kacc_geom(chs, Kp, pxs)
    # PBK: the kernel re-sends the b block for every a tile -> b traffic ~ H*M*N*KW/4 bytes, so for a short K
    # (default walk nkc <= 4) keep K at its 64-pad and take the whole K in ONE chunk (tkw = Kp/2 <= 32), splitting
    # px until the ping-pong windows fit (c004: 1024x40x1024 -> tkw 32, px 256, 4 launches/head).
    tkwf = 0
    if geo["nkc"] <= 4 and Kp // 2 <= 32 and not geo["tr"]:
        for s1 in (1, 2, 4, 8):
            if Mp % (64 * s1) == 0:
                try:
                    g1 = ua.kacc_geom(Np, Kp, Mp // s1, Kp // 2)
                except AssertionError:
                    continue
                if not g1["tr"]:
                    tkwf, geo, chs, pxs, S, mode = Kp // 2, g1, Np, Mp // s1, s1, ("px" if s1 > 1 else "none")
                    break
    # PBK probe: c013 (nkc 4) and c004 (nkc 4) came back wrong on the board (cos 0.64 / 0.31), c014 (nkc 9) and
    # c005 (nkc 16) right -> one more zero 64-K block whenever the K walk would be exactly 4 chunks
    while geo["nkc"] == 4 and not tkwf:
        Kp += 64
        geo = ua.kacc_geom(chs, Kp, pxs)
    import os
    if os.environ.get("KACC_BMM_KP"):  # probe override
        Kp = int(os.environ["KACC_BMM_KP"])
        geo = ua.kacc_geom(chs, Kp, pxs)
    kch, kp, tr = geo["kch"], geo["kp"], geo["tr"]
    # x86 self-check of the recipe (what the AIE should reach): bf16 operands, fp64 acc, bf16 out
    f = lambda u: (u.astype(np.uint32) << 16).view(np.float32).astype(np.float64)
    ref = f(bf16((f(bf16(a[0])) @ f(bf16(b[0]))).astype(np.float32)))
    yr = y.reshape(ref.shape).astype(np.float64)
    cos = (ref * yr).sum() / np.sqrt((ref * ref).sum() * (yr * yr).sum())
    gmac = H * Mp * Np * Kp / 1e9
    print(f"[kacc_gemm] bmm H={H} M={M} K={K} N={N} pad(M,K,N)=({Mp},{Kp},{Np}) split={mode} S={S} "
          f"instance=(ch {chs}, k {Kp}, px {pxs}) kch={kch} kp={kp} tkw={geo['tkw']} nkc={geo['nkc']} tr={tr} l1={geo['l1']} launches={H * S} "
          f"gmac_padded={gmac:.4f} x86 bf16-recipe vs golden cos={cos:.6f} y_sha256={ysha}")
    np.ascontiguousarray(a[0]).astype("<f4").tofile(out / "kacc_a.bin")   # natural [H][M][K] f32: packed at run time
    np.ascontiguousarray(b[0]).astype("<f4").tofile(out / "kacc_b.bin")   # natural [H][K][N] f32: packed at run time
    y.astype("<f4").reshape(-1).tofile(out / "kacc_y.bin")
    data = "op_golden/" + "/".join(str(g).rstrip("/").split("/")[-2:])
    tag = data.split("/")[-1][:4] + "-kacc-bmm"
    inc = lambda n: f'    ".balign 64\\n.global {n}\\n{n}:\\n.incbin \\"{out}/{n[:-4]}.bin\\"\\n"\n'
    (out / "kacc_data.h").write_text(f"""/* generated by kacc_gemm.py --bmm (kacc_bench.sh --bmm) from {g} */
#ifndef KACC_DATA_H
#define KACC_DATA_H
#include "unistd.h"
#include "xil_cache.h"
#include "xiltimer.h"
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#define KACC_H {H}
#define KACC_M {M}
#define KACC_MP {Mp}
#define KACC_K {K}
#define KACC_KP {kp}
#define KACC_KCH {kch}
#define KACC_N {N}
#define KACC_NP {Np}
#define KACC_S {S}
#define KACC_SPLIT_PX {int(mode == "px")}
#define KACC_CHS {chs}
#define KACC_PXS {pxs}
#define KACC_TR {tr}
#define KACC_GMAC {gmac:.6f}
#define KACC_DATA "{data}"
#define KACC_TAG "{tag}"
#define KACC_Y_SHA "{ysha}"
#if defined(__aarch64__)
__asm__(".section .rodata.kacc,\\"a\\"\\n"
{inc("kacc_a_bin")}{inc("kacc_b_bin")}{inc("kacc_y_bin")}    ".previous\\n");
extern "C" const uint8_t kacc_a_bin[], kacc_b_bin[], kacc_y_bin[];
#else
static const uint8_t kacc_a_bin[64] = {{0}}, kacc_b_bin[64] = {{0}}, kacc_y_bin[64] = {{0}};
#endif
#endif
""")
    name = ua.kacc_name(chs, Kp, pxs)
    args = "Xs, Ws, Ys" if tr else "Ws, Xs, Ys"
    src = (ua.CTRLPKT_PRAGMAS + "// kacc_gemm.cc -- generated by kacc_gemm.py --bmm: gemm_kacc as attention bmm (PBK)\n"
           "#define UNET_KACC_KERNEL 1\n#include \"kacc_data.h\"\n#include \"aie_kacc_pack.h\"\n\n" +
           ua.kacc_kernel_text(chs, Kp, pxs, tkwf) + "\n" + HOST_BMM.replace("@NAME@", name).replace("@ARGS@", args))
    (out / "kacc_gemm.cc").write_text(src)
    print(f"[kacc_bench] data={data} tag={tag} kernel={name} launches_per_pass={H * S}")


