def runtime_io_main(base: str) -> str:
    """MAIN_C (or its --aie conv form) -> inputs from .aiehlc_io; ref compare only for the build's own input"""
    assert base.count(RTIO_COPY_OLD) == 1, "MAIN_C input block changed"
    s = base.replace(RTIO_COPY_OLD, RTIO_COPY_NEW, 1)
    inc = '#include "p1_ref.h"\n'
    assert s.count(inc) == 1
    s = s.replace(inc, inc + '#include "aiehlc_io.h"\n', 1)
    m = re.search(r'^    int rc = p1_cmp\("unet[^;]*\);\n', s, re.M)
    assert m, "p1_cmp call not found"
    call = m.group(0)
    launches = "launches" if "unet_aie_stats(&launches" in s else "0"
    runrc = "run_rc" if launches == "launches" else "0"
    new = ("    int rc;\n"
           "    if (unet_rtio_own)\n"
           "        " + call.strip().replace("int rc = ", "rc = ") + "\n"
           "    else {\n"
           '        printf("CMP unet skipped runtime-input aie_launches=%d run_rc=%d\\n", '
           + launches + ", " + runrc + ");\n"
           "        fflush(stdout);\n"
           "        rc = " + runrc + " != 0;\n"
           "    }\n"
           "    if (aiehlc_io_dump_out())\n"
           '        aiehlc_io_dump("unet", out, (unsigned long)n * sizeof(float), (unsigned long)n);\n')
    return s.replace(call, new, 1)


def log(msg):
    print(f"[build_unet] {msg}", flush=True)


def c_array(ctype, name, vals, fmt):
    body = ",\n".join(", ".join(fmt(v) for v in vals[i:i + 8]) for i in range(0, len(vals), 8))
    return f"static const {ctype} {name}[{len(vals)}] __attribute__((aligned(64))) = {{\n{body}\n}};\n"


def write_inputs_header(real_io: Path, path: Path, aie: str, wdtype: str = "fp32") -> str:
    s = np.fromfile(real_io / "sample.bin", dtype="<f4")
    t = np.fromfile(real_io / "timestep_i32.bin", dtype="<i4")
    e = np.fromfile(real_io / "ehs.bin", dtype="<f4")
    assert s.size == 4 * 32 * 32 and t.size == 1 and e.size == 77 * 768, (s.size, t.size, e.size)
    t64 = np.fromfile(real_io / "timestep_i64.bin", dtype="<i8")
    assert int(t64[0]) == int(t[0]), (t64, t)
    crc = "%08x" % zlib.crc32(s.tobytes() + t.tobytes() + e.tobytes())
    want = (real_io / "unet_in.crc32").read_text().strip()
    assert crc == want, (crc, want)
    f = lambda v: repr(float(v)) + "f" if np.isfinite(v) else "0.0f"
    hx = lambda v: "%.9ef" % float(v)
    txt = ["/* generated by build_unet.py from %s -- do not edit */" % real_io,
           "#pragma once", "#include <stdint.h>",
           '#define UNET_AIE_MODE "%s"' % aie, '#define UNET_WDTYPE "%s"' % wdtype,
           "#define UNET_N_INPUTS 3",
           c_array("float", "unet_sample", s, hx),
           c_array("int32_t", "unet_timestep", t, lambda v: "%d" % int(v)),
           c_array("float", "unet_ehs", e, hx),
           'static const char *const unet_in_name[3] = {"sample", "timestep", "encoder_hidden_states"};',
           "static const void *const unet_in_ptr[3] = {unet_sample, unet_timestep, unet_ehs};",
           "static const unsigned long unet_in_bytes[3] = {%d, %d, %d};"
           % (s.nbytes, t.nbytes, e.nbytes), ""]
    path.write_text("\n".join(txt))
    # the header must round-trip bit-exactly
    log(f"inputs: sample {s.size} f32, timestep {int(t[0])} i32, ehs {e.size} f32; "
        f"crc32(sample+t_i32+ehs)={crc} == unet_in.crc32")
    return crc


def timestep_to_i32(src: Path, dst: Path) -> Path:
    """Rewrite input 'timestep' int64 -> int32 + Cast(to int64) feeding the old consumers."""
    import onnx
    from onnx import TensorProto, helper
    if dst.is_file() and dst.stat().st_mtime > src.stat().st_mtime:
        log(f"reuse {dst}")
        return dst
    m = onnx.load(str(src))
    inp = next(i for i in m.graph.input if i.name == "timestep")
    assert inp.type.tensor_type.elem_type == TensorProto.INT64, inp
    inp.type.tensor_type.elem_type = TensorProto.INT32
    for n in m.graph.node:
        n.input[:] = ["timestep_i64" if x == "timestep" else x for x in n.input]
    m.graph.node.insert(0, helper.make_node("Cast", ["timestep"], ["timestep_i64"],
                                            to=TensorProto.INT64, name="timestep_i32_to_i64"))
    onnx.checker.check_model(m) if m.ByteSize() < 2**31 - 1 else None
    tmp = dst.with_suffix(".tmp.onnx")
    onnx.save(m, str(tmp))
    tmp.replace(dst)
    log(f"timestep int64 -> int32 input + Cast: {dst} ({dst.stat().st_size:,} B)")
    return dst


def keep_layout_step(ua, onnx_path, part: dict, layers: list, out: Path):
    """GAP-B: partition rows with ``keep_layout`` -- the output stays in the AIE layout, Transposes / Reshapes
    to its AIE consumers are labels only (aiegraph.partition.plan_keep_layout). Tags ``layers``, writes
    <out>/keep_layout.json, prints KEEP_LAYOUT. None when no row has the field (build unchanged)."""
    if not any(L.get("keep_layout") for L in part["layers"]):
        return None
    keep = ua.keep_layout_plan(onnx_path, part, layers)
    out.mkdir(parents=True, exist_ok=True)
    (out / "keep_layout.json").write_text(json.dumps(keep, indent=1))
    log(f"KEEP_LAYOUT edges={keep['kept']} label_ops={keep['label_ops']} "
        f"consumers={sum(len(e['consumers']) for e in keep['edges'])} ({out / 'keep_layout.json'})")
    return keep


def fa_offload_groups(emod, att: list, kcc: Path, out: Path) -> int:
    """S3 (design 2026-11-16 §5.2): every attention group = one aiegraph group offload with the four FA steps
    (fa_attn.FA_STEPS, checked against their AIEK_STEP declarations); aiegraph places them, removes the other
    calls (QK bmm, softmax, O merge) after its liveness / external-reader / early-write checks, and records the
    group in layers/partition.json, from which arm_build emits the driver."""
    import aiegraph as ag
    import fa_attn
    from aiegraph.group import reset_groups
    stepsrc = out / "aiek_src" / "fa_steps.cc"
    stepsrc.write_text(fa_attn.fa_steps())
    specs = ag.load_steps(stepsrc)
    reset_groups(emod.workdir)
    by = {}
    for c in att:
        by.setdefault(c["ag_group"].name, {})[c["role"]] = c
    ncalls = 0
    for name, d in by.items():
        qk, pv = d["qk"], d["pv"]
        g = qk["ag_group"]
        if qk["fa"] != pv["fa"] or qk["fa"] != g.cls:
            raise SystemExit(f"{name}: FA class {qk['fa']}/{pv['fa']} != aiegraph class {g.cls}")
        steps = fa_attn.fa_group_steps(ag, g, qk["cid"], pv["cid"], qk["fa"])
        ag.check_steps(specs, steps)
        plan = emod.offload_group(g, source=str(kcc), steps=steps, emit=fa_attn.fa_step_emit(g))
        want = {"fa_step_pack_q": g.q_call, "fa_step_pack_k": g.k_call, "fa_step_pack_v": g.v_call,
                "fa_step_run_o": g.pv}
        if plan.placement != want or sorted(plan.removed) != sorted([g.qk, g.softmax, g.merge]):
            raise SystemExit(f"{name}: placement {plan.placement} removed {plan.removed}, expected {want} "
                             f"removed {[g.qk, g.softmax, g.merge]}")
        for c in (qk, pv):
            c["fa_steps"] = True
        ncalls += len(g.calls)
    log(f"FA_GROUPS groups={len(by)} calls={ncalls} steps={4 * len(by)} removed={3 * len(by)} "
        f"(aiegraph offload_group, layers/partition.json)")
    return len(by)


def aie_conv(a, emod, out: Path, hdr: Path):
    """--aie conv: map partition layers, build the AIE archive on a carrier layer,
    patch every partition call site in graph_driver.c. Returns (main.c, n_sites)."""
    import aiegraph._env as env
    env.frontend("")
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import unet_aie as ua
    import aiegraph as ag
    import frontend.tvmrelay.arm_build as ab
    import onnx
    from aiegraph.callsite import all_conv_calls
    part = json.loads(a.partition.resolve().read_text())
    work = Path(emod.workdir)
    # S1 (unet-m3): aiegraph matches every partition conv / linear row to its TVM call -- one group
    # of one call each (g.x / g.y / g.w / g.info); the steps are placed by emod.offload_group below
    onnx_model = onnx.load(str(a.onnx.resolve()))
    cgroups = emod.match("conv", partition=part, model=onnx_model)
    folded = [g.info["onnx"] for g in cgroups if g.info["folded"]]
    assert all("proj_in" in x for x in folded), f"weight mismatch outside proj_in: {folded}"
    sel = [dict(g.info, group=g) for g in cgroups]
    for c in sel:
        launches = ua.ceil64(c["M"]) * ua.ceil64(c["N"]) * ua.ceil64(c["K"])
        L = next(L for L in part["layers"] if L["idx"] == c["cid"])
        assert launches == L["launches"], (c["onnx"], launches, L["launches"])
        c["launches"] = launches
    convs = all_conv_calls(emod.call_graph())
    log(f"aiegraph match('conv'): {len(sel)} partition conv layers -> one-call groups "
        f"({len(convs)} TVM conv calls, {len(folded)} with a TVM-folded weight: proj_in)")
    nlin_part = sum(1 for L in part["layers"] if L.get("cls") == "linear")
    lin = []
    if "linear" in a.aie.split(","):
        # PDN: the partition's linear layers (TVM nn_contrib_dense_pack) -> unet_aie_linear, gemm_kacc
        lin = [dict(g.info, group=g) for g in emod.match("linear", partition=part, model=onnx_model)]
        for c in lin:
            c["S"], c["pxs"] = ua.kacc_split(c["N"], c["K"], -(-c["M"] // 64) * 64)
            c["launches"] = c["S"]
        log(f"aiegraph match('linear'): {len(lin)} partition linear layers -> one-call groups "
            f"(weights equal by value), {sum(c['S'] for c in lin)} gemm_kacc launches")
        if len(lin) != nlin_part:
            raise SystemExit(f"mapped {len(lin)} linear layers, partition has {nlin_part}")
    elif nlin_part:
        raise SystemExit(f"partition has {nlin_part} linear layers: build with --aie conv,linear")
    del onnx_model
    if lin and not a.kincore:
        raise SystemExit("--aie conv,linear needs --kincore (gemm_kacc)")
    att = []
    if "attn" in a.aie.split(","):
        # GATT: the partition's attention bmm layers (TVM nn_batch_matmul) -> unet_aie_attn, gemm_kacc + runtime pack
        natt_part = sum(1 for L in part["layers"] if L.get("cls") == "attn")
        if not natt_part:
            raise SystemExit("--aie conv,linear,attn: partition has no attn layers (autopart --mode attn)")
        if not a.kincore:
            raise SystemExit("--aie conv,linear,attn needs --kincore (gemm_kacc)")
        att = ua.map_attn(part, work, onnx=a.onnx.resolve())   # S3: aiegraph attention matcher
        if len(att) != natt_part:
            raise SystemExit(f"mapped {len(att)} attn layers, partition has {natt_part}")
    fa = []
    if a.attn_fa:
        # GFA (P2): each attention group = ONE flash-attention (online softmax) on the AIE; TVM softmax removed
        if not att:
            raise SystemExit("--attn-fa needs --aie conv,linear,attn")
        import fa_attn
        fa = fa_attn.fa_classes(att)
        for c in att:
            c["launches"] = fa[c["fa"]]["launches"] if c["role"] == "pv" else 0
        for k in fa:
            log(f"GFA class {k['idx']} {k['name']} split={k['split']} nkv={k['nkv']} kvl={k['kvl']} units={k['units']} "
                f"launches/site={k['launches']}")
    keep = keep_layout_step(ua, a.onnx.resolve(), part, sel + lin + att, out)
    if a.kincore:
        # P4bg: one launch per layer from kplan.py (K in the core) -- the partition.json N (64x64x64
        # tile launches) does not apply on this path
        import kplan
        if a.kincore_layers != "all":
            # P4bp: probe subset -- unselected layers keep their TVM C call site (no aiegraph group for them)
            want = sorted({int(x) for x in a.kincore_layers.split(",") if x.strip()})
            bad = [i for i in want if not 0 <= i < len(sel)]
            if not want or bad:
                raise SystemExit(f"--kincore-layers {a.kincore_layers}: indices must be in 0..{len(sel) - 1}")
            sel = [sel[i] for i in want]
            log(f"KINCORE subset --kincore-layers {','.join(map(str, want))} -> cids {[c['cid'] for c in sel]}")
        for c in sel:
            kp = kplan.plan(c["M"], c["K"], c["N"])
            if not kp["legal"] or kp["launches"] != 1:
                raise SystemExit(f"kplan: layer {c['cid']} M={c['M']} K={c['K']} N={c['N']} "
                                 f"legal={kp['legal']} launches={kp['launches']} why={kp['why']}")
            c["launches"] = kp["launches"]
        convsel = sel
        sel = sel + lin
        planned = sum(c["launches"] for c in sel + att)
        shapes = sorted({(c["N"], c["K"], c["M"]) for c in convsel} | {(c["N"], c["K"], c["pxs"]) for c in lin} |
                        (set() if fa else set(ua.attn_shapes(att))))
        log(f"KINCORE layers={len(sel) + len(att)} launches_planned={planned} kernel=bf16_gemm_kacc; "
            f"shapes={len(shapes)} (old 64x64x64 launches {part['N']})")
    else:
        convsel = sel
        planned = sum(c["launches"] for c in sel)
        if planned != int(part["N"]):
            raise SystemExit(f"planned launches {planned} != partition.json N {part['N']}")
    if att:
        log(f"aie_launches_planned={planned} (partition.json N={part['N']}, {len(sel) + len(att)} layers: "
            f"{len(sel) - len(lin)} conv + {len(lin)} linear + {len(att)} attn, "
            f"{sum(c['macs'] for c in sel + att)} MACs of {part['total_gemm_macs']} GEMM MACs)")
    else:
        log(f"aie_launches_planned={planned} (partition.json N={part['N']}, {len(sel)} layers: "
            f"{len(sel) - len(lin)} conv + {len(lin)} linear, "
            f"{sum(c['macs'] for c in sel)} MACs of {part['total_gemm_macs']} GEMM MACs)")
    for c in sel:
        if c.get("kind") == "linear":
            log(f"  aie linear {c['cid']:3d} {c['onnx']} -> node {c['node']} {c['func']} "
                f"M={c['M']} N={c['N']} K={c['K']} px_split={c['S']}x{c['pxs']} launches={c['launches']}")
        else:
            log(f"  aie conv {c['cid']:2d} {c['onnx']} -> node {c['node']} {c['func']} "
                f"M={c['M']} N={c['N']} K={c['K']} s={c['sh']} p={c['ph']} launches={c['launches']}")
    for c in att:
        g = c["geo"]
        log(f"  aie attn {c['cid']:3d} {c['role']} g{c['group']} {c['onnx']} -> node {c['node']} {c['func']} "
            f"H={g['H']} M={c['M']} K={c['K']} N={c['N']} swap={g['swap']} ch={g['chs']} k={g['Kp']} px={g['pxs']} "
            f"S={g['S']} launches={c['launches']}")
    ua.check_data_arg0(work / "layers", convsel)
    lidx, car = ua.pick_carrier(convsel, convs, work / "layers")
    log(f"carrier layer {lidx} ({car['func']}): aiegraph offload builds the gemm_bf16 archive on it")
    p = emod.offload_prototype(lidx, entry=ua.ENTRY)
    if a.kincore:
        kcc = ua.write_kernel_kacc(out / "aiek_src", p.spec(), shapes, warm=(a.launch_opt == "warm"),
                                   ctrlpkt=a.ctrlpkt,
                                   lin=[(c["N"], c["K"], -(-c["M"] // 64) * 64, c["pxs"]) for c in lin],
                                   **({"att": att} if att else {}), **({"fa": fa} if fa else {}))
    else:
        kcc = ua.write_kernel(out / "aiek_src", p.spec(), max(c["M"] * c["N"] for c in sel),
                              warm=(a.launch_opt == "warm"), ctrlpkt=a.ctrlpkt, ktimer=a.ktimer)
    if a.ctrlpkt == "aot":
        log(f"ctrlpkt=aot pragmas={ua.CTRLPKT_NPRAGMAS}")
    log(f"kernel source {kcc}")
    if fa:
        fa_offload_groups(emod, att, kcc, out)

    # S1: conv / linear call sites through aiegraph -- one-call groups, the "args" step ABI, bf16 weights
    # pre-laid out for gemm_kacc in weights.bin (aiegraph drops their graph_bf16_expand)
    if not a.kincore:
        raise SystemExit("aiegraph conv/linear groups need --kincore (kacc weight layout)")
    nw = 0
    for c in sel:
        g = c["group"]
        if c["kind"] == "linear":
            st = ag.step("unet_aie_linear", reads=g.x, writes=g.y,
                         weights=g.w.as_bf16(layout=lambda w, c=c: ua.kacc_dense_wlayout(w, c["N"], c["K"], c["pxs"])),
                         consts=dict(cid=c["cid"], S=c["S"]), call=("cid", "args", "nargs", "wbf", "S"),
                         wrap=("UP_AIE_BEGIN", "UP_AIE_END"), tag=f"aie unet_aie_lin {c['cid']}")
        else:
            st = ag.step("unet_aie_conv", reads=g.x, writes=g.y,
                         weights=g.w.as_bf16(layout=lambda w, c=c: ua.kacc_wlayout(w, c["N"], c["K"], c["M"])),
                         consts=dict(cid=c["cid"], sh=c["sh"], sw=c["sw"], ph=c["ph"], pw=c["pw"]),
                         call=("cid", "args", "nargs", "wbf", "sh", "sw", "ph", "pw"),
                         wrap=("UP_AIE_BEGIN", "UP_AIE_END"), tag=f"aie unet_aie_conv {c['cid']}")
        plan = emod.offload_group(g, kcc, steps=[st])
        nw += plan.steps[0]["weights"]["nbytes"]
    log(f"aiegraph offload_group: {len(sel)} one-call groups ({len(sel) - len(lin)} unet_aie_conv + "
        f"{len(lin)} unet_aie_linear), WPRE bf16 kacc-layout weights {nw} B (layers/partition.json groups)")

    # S6: the C glue (FA kernel declarations, PROF macros, expand timing) is the driver template that
    # aiegraph places at checked anchors of every generated driver -- registered before keep_layout so
    # it runs first; the build_unet.py side only declares groups + this template
    emod.driver_template(**ua.driver_template(att))
    n = len(sel) + len(att)
    log(f"graph_driver.c: {n} partition call sites -> unet_aie_conv ({n - len(lin) - len(att)}) + "
        f"unet_aie_linear ({len(lin)})" + (f" + unet_aie_attn ({len(att)})" if att else "") +
        " (aiegraph group steps + driver template)")

    if a.keep_layout:
        # P4a/S5: keep the AIE layout between layers -- aiegraph codegen (keep_layout_codegen) runs on every
        # generated driver: the A78 head split/merge, transformer-out and conv-out layout ops + the temb weight
        # re-pack go; partition keep_layout edges (plan_keep_layout) carry the producer's graph.json node
        plan = None
        if keep is not None:
            by = {c.get("onnx"): c for c in sel + lin + att}
            plan = dict(keep, edges=[dict(e, node_id=by[e["node"]]["node"]) for e in keep["edges"]])
        emod.keep_layout(plan, log=log)
    # gates 3-4 = aiegraph's group-level x86 check (TVM's C vs the step's x86 model, cos >= 0.999,
    # nonfinite == 0), binding: a failing carrier is rejected and the build stops below
    rep = emod.offload(f"layer{lidx}", str(kcc), check="group", verbose=a.verbose)
    log(f"offload: {rep}")
    lp = json.loads((work / "layers" / "partition.json").read_text())
    if not any(L.get("target") == "aie" and L.get("archive") for L in lp["layers"]):
        raise SystemExit("offload FAILED: carrier layer has no AIE archive in layers/partition.json")
    if a.launch_opt == "warm":
        with open(hdr, "a") as f:
            f.write('#define UNET_LAUNCH_WARM 1\n#define UNET_LAUNCH_OPTS "%s"\n' % LAUNCH_OPTS_WARM)
    with open(hdr, "a") as f:
        f.write('#define UNET_CTRLPKT "%s"\n' % a.ctrlpkt)
    with open(hdr, "a") as f:
        f.write("#define UNET_AIE_PLANNED_LAUNCHES %d\n#define UNET_AIE_PLANNED_CALLS %d\n"
                "#define UNET_TOTAL_GEMM_MACS %dULL\n" % (planned, len(sel) + len(att), int(part["total_gemm_macs"])))
    if keep is not None:
        with open(hdr, "a") as f:
            f.write("#define UNET_KEEP_LAYOUT_EDGES %d\n" % keep["kept"])
    log(f"ktimer={'on' if a.ktimer else 'off'}")
    return ua.main_c(MAIN_C, ktimer=a.ktimer), (len(sel) - len(lin), len(lin), len(att))


def read_layer_cflags_file(path) -> str:
    """--arm-layer-cflags-file: the file's lines joined with single spaces.
    A missing or empty (whitespace-only) file is an error, never a silent ''."""
    path = Path(path)
    if not path.is_file():
        raise ValueError(f"--arm-layer-cflags-file {path}: no such file")
    flags = " ".join(path.read_text().split())
    if not flags:
        raise ValueError(f"--arm-layer-cflags-file {path}: file is empty")
    return flags


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--onnx", required=True, type=Path)
    ap.add_argument("--real-io", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    ap.add_argument("--attn-fa", action="store_true",
                    help="GFA (P2): with --aie conv,linear,attn, every attention group (QK bmm, softmax, PV bmm) runs as "
                         "ONE flash-attention (online softmax, fa_attn.py) on the AIE -- an aiegraph group offload "
                         "(S3): pack Q/K/V + run O steps, the other group calls (softmax included) removed by aiegraph")
    ap.add_argument("--keep-layout", action="store_true",
                    help="P4a (needs --attn-fa): keep the AIE layout between layers (aiegraph keep_layout_codegen) -- FA packs read "
                         "the linear outputs by stride (TVM head split/merge ops removed), temb dense weights pre-packed "
                         "in weights.bin (TVM per-call W*s re-pack removed)")
    ap.add_argument("--aie", choices=("none", "conv", "conv,linear", "conv,linear,attn"), default="none",
                    help="conv,linear (PDN): also the partition's linear layers (dense) on the AIE (needs --kincore); "
                         "conv,linear,attn (GATT): also the attention bmm layers (cls=attn) -> unet_aie_attn, "
                         "PROF op=aie_host_attn<N> (needs --kincore)")
    ap.add_argument("--wdtype", choices=("fp32", "bf16"), default="fp32",
                    help="bf16: weights.bin holds bf16 (RNE); each APU call expands its "
                         "weights into one static .bss fp32 scratch (~118 MB)")
    ap.add_argument("--partition", type=Path, default=None,
                    help="--aie conv: p35/partition.json (layers on the AIE, planned N)")
    ap.add_argument("--launch-opt", choices=("cold", "warm"), default="cold",
                    help="warm (P5): aiehlc --skip-bss + ZFILL_WIDE/PMLOAD_WIDE/PM_WARM_SKIP: the conv "
                         "kernel is loaded once, later launches only reset the cores (CoreReset+Unreset), "
                         "rewrite .data/BDs/locks, enable and wait")
    ap.add_argument("--ctrlpkt", choices=("off", "aot", "aot-kco"), default="off",
                    help="aot (P2a): control-packet plan pragmas in aiek_unetconv.cc + "
                         "__Runtime_ctrl_high_throughput_enable(1) before the first launch; "
                         "aot-kco: aot + #pragma KERNELCONFIGOFFLOAD (sets UNET_CTRLPKT_KCO=1, see unet_aie.CTRLPKT_KCO)")
    ap.add_argument("--ktimer", action="store_true",
                    help="gemm_bf16 reads the AIE core timer at entry/exit into a 4-word tail per C block "
                         "(ports b 80x64 / c 64x80, bf16_gemm_convin_ktimer.cc); main prints KTIMER. "
                         "Default off: 64x64 ports, no timer reads")
    ap.add_argument("--kincore", action="store_true",
                    help="P4bg: one launch per conv layer (kplan.py), Maxwell's K-accumulating gemm_kacc "
                         "(bf16_gemm_kacc.cc) instantiated per layer shape; host does im2col + pre-tiling, "
                         "no host K sum. Default off: 64x64x64 gemm_bf16 tiles (partition.json N launches)")
    ap.add_argument("--kincore-layers", default="all",
                    help="P4bp: --kincore only -- comma-separated partition layer indices (0..36) put on the AIE; "
                         "the others keep their TVM C call site. Default all")
    ap.add_argument("--arm-layer-cflags-file", type=Path, default=None,
                    help="file of extra CFLAGS for the TVM per-layer kernel objects only (liblayers.a; "
                         "arm_build layer_cflags). Lines are joined with spaces and passed as ONE string, "
                         "so no shell word-splitting. Missing or empty file -> error. Default: none")
    ap.add_argument("--runtime-io", action="store_true",
                    help="GIN: inputs in the .aiehlc_io ELF section (arm_build.write_runtime_io), swappable "
                         "after the build with src/tool/elfio/aiehlc_elfio.py patch; initialised from --real-io")
    ap.add_argument("--dump-out", action="store_true",
                    help="--runtime-io: set the section's dump_out flag at build time (AIO_* output dump)")
    ap.add_argument("--verbose", action="store_true")
    a = ap.parse_args(argv)
    if a.ctrlpkt == "aot-kco":  # before unet_aie is imported: it reads UNET_CTRLPKT_KCO at import time
        os.environ["UNET_CTRLPKT_KCO"] = "1"
        a.ctrlpkt = "aot"
    elif "unet_aie" not in sys.modules:
        os.environ.pop("UNET_CTRLPKT_KCO", None)
    layer_cflags = ""
    if a.arm_layer_cflags_file is not None:
        try:
            layer_cflags = read_layer_cflags_file(a.arm_layer_cflags_file)
        except ValueError as e:
            log(str(e))
            return 2
        log(f"arm_layer_cflags ({a.arm_layer_cflags_file}): {layer_cflags}")
    if a.aie != "none":
        if a.partition is None or a.wdtype != "bf16":
            log("--aie conv needs --partition <partition.json> and --wdtype bf16")
            return 2
        # PH_COREEN is counted only by a runtime built with -DAIEHLC_PROFILING=1 (as P2/P3)
        os.environ["AIEHLC_PROFILING"] = "1"
        os.environ["EXTRA_DEFS"] = (os.environ.get("EXTRA_DEFS", "") + " -DAIEHLC_PROFILING=1").strip()
    if a.keep_layout and not a.attn_fa:
        log("--keep-layout needs --attn-fa")
    if a.dump_out and not a.runtime_io:
        log("--dump-out needs --runtime-io")
        return 2
    if a.kincore_layers != "all" and not a.kincore:
        log("--kincore-layers needs --kincore")
        return 2
    if a.kincore and (a.aie == "none" or a.ktimer):
        log("--kincore needs --aie conv and no --ktimer")
        return 2
    if a.ctrlpkt == "aot" and a.aie == "none":
        log("--ctrlpkt aot needs --aie conv")
        return 2
    if a.launch_opt == "warm":
        if a.aie == "none":
            log("--launch-opt warm needs --aie conv")
            return 2
        # --skip-bss is safe for gemm_bf16: its .bss is the 6 DMA port buffers (filled by DMA /
        # written by the kernel before any read), aiehlc_cur_a/b/c (block cursors, only feed
        # klog, compiled out) and softfloat's float_rounding_mode (read by float32_add/mul,
        # never written) -- the kernel zeroes the latter on every launch (unet_aie.SOFTFLOAT_RM).
        os.environ["AIEHLC_SH_ARGS"] = "--skip-bss"
        os.environ["EXTRA_DEFS"] = (os.environ["EXTRA_DEFS"] + " " + WARM_DEFS).strip()
        log(f"launch_opt=warm defs={os.environ['EXTRA_DEFS']} aiehlc.sh={os.environ['AIEHLC_SH_ARGS']} "
            f"(AIEHLC_BD_WARM_SKIP not added: no Amit hardware ack in the channel)")
    out = a.out.resolve()
    real_io = a.real_io.resolve()
    out.mkdir(parents=True, exist_ok=True)

    # the gate runs plain $AGPY (no PYTHONPATH): use this checkout's aiegraph
    mi = Path(__file__).resolve().parents[3] / "src"
    if mi.is_dir() and str(mi) not in sys.path:
        sys.path.insert(0, str(mi))
    import aiegraph as ag
    root = Path(ag.__file__).resolve().parents[2]
    os.environ.setdefault("AIEHLC_ROOT", str(root))
    # 1.29 GB fp32 weights: read in place from the linked blob (no 2nd .bss copy)
    os.environ["AIEGRAPH_PARAMS_INPLACE"] = "1"
    os.environ["AIEGRAPH_WDTYPE"] = a.wdtype
    # GHL: the aiek host.cc carries the per-site im2col / scatter glue (A78 time inside graph_run); hostcompile.sh
    # builds it -Os unless HOSTCOMPILE_HOST_OPT is set (runtime .c files and kernels keep -Os)
    os.environ.setdefault("HOSTCOMPILE_HOST_OPT", "-O2")
    log(f"aiegraph from {ag.__file__} (repo {root})")
    log(f"HOSTCOMPILE_HOST_OPT={os.environ['HOSTCOMPILE_HOST_OPT']} (aiek host.cc)")

    hdr = out / "unet_inputs.h"
    write_inputs_header(real_io, hdr, a.aie, a.wdtype)

    onnx_i32 = timestep_to_i32(a.onnx.resolve(), out / "unet_sim_t32.onnx")
    m = ag.load(str(onnx_i32))
    log(f"loaded {m.name}: inputs {m.input_shapes} -> {m.output_shape}, "
        f"{sum(m.ops.values())} nodes {m.ops}")
    # a fresh conversion every build (the driver and weights.bin of ag_work are rewritten below)
    shutil.rmtree(out / "ag_work", ignore_errors=True)
    emod = m.convert(target="a78", quantize="fp32", image=str(real_io / "sample.bin"),
                     workdir=out / "ag_work", verbose=a.verbose)
    log(f"converted -> {emod.workdir} ({emod.state.get('layer_count') if hasattr(emod, 'state') else '?'} layers)")
    if not shutil.which("aarch64-none-elf-gcc"):
        # the gate runs plain $AGPY: take the cross toolchain from the repo setup
        import subprocess
        env = subprocess.run(["bash", "-c", f"cd {root} && source script/setup.sh "
                              "--path-set-only >/dev/null 2>&1; env -0"],
                             capture_output=True, check=True).stdout.decode()
        os.environ.update(kv.split("=", 1) for kv in env.split("\0") if "=" in kv)
        log(f"toolchain via {root}/script/setup.sh: {shutil.which('aarch64-none-elf-gcc')}")
    main_c = MAIN_C
    if a.aie != "none":
        main_c, n_patched = aie_conv(a, emod, out, hdr)

    extra = [P1_COS_C, real_io / "p1_ref.h", hdr]
    if a.runtime_io:
        import aiegraph._env as agenv
        agenv.frontend("")
        import frontend.tvmrelay.arm_build as ab
        main_c = runtime_io_main(main_c)
        extra += ab.write_runtime_io(out / "runtime_io", [
            ("sample", real_io / "sample.bin"), ("timestep_i32", real_io / "timestep_i32.bin"),
            ("ehs", real_io / "ehs.bin")], dump_out=a.dump_out)
        log(f"runtime_io: inputs in {ab.AIO_SECTION} (sample, timestep_i32, ehs), dump_out={int(a.dump_out)}")
    rep = emod.build(target="a78", verbose=a.verbose, main_c=main_c,
                     extra_sources=extra,
                     extra_cflags="-DP1_COS_NO_MAIN " + HEAP_LDFLAG,
                     layer_cflags=layer_cflags)
    if not rep.ok:
        log(f"build FAILED: {rep.reason}")
        return 1
    if a.aie != "none":
        drv = (Path(rep.elf).parent / "graph_driver.c").read_text()
        # P4a --keep-layout: an FA group's QK / PV site = unet_aie_attn_kl role 3 (K pack) / role 6 (launch + O)
        nkl = len(re.findall(r"    unet_aie_attn_kl\(\d+, [36], ", drv))
        got = (drv.count("    unet_aie_conv("), drv.count("    unet_aie_linear("), drv.count("    unet_aie_attn(") + nkl)
        if got != n_patched:
            log(f"build FAILED: linked driver has {got} unet_aie_conv/unet_aie_linear/unet_aie_attn call sites, "
                f"expected {n_patched}")
            return 1
        log(f"linked driver: {got[0]} call sites -> unet_aie_conv + {got[1]} -> unet_aie_linear (AIE), "
            f"weights of those read as bf16 in place" + (f"; {got[2]} -> unet_aie_attn" if got[2] else ""))
    elf = out / "main.elf"
    shutil.copy2(rep.elf, elf)
    if a.runtime_io:
        import subprocess
        tool = Path(__file__).resolve().parents[3] / "src" / "tool" / "elfio" / "aiehlc_elfio.py"
        r = subprocess.run([sys.executable, str(tool), "info", str(elf)], capture_output=True, text=True)
        for ln in (r.stdout + r.stderr).splitlines():
            log(ln)
        if r.returncode != 0:
            log("build FAILED: main.elf has no loadable .aiehlc_io section")
            return 1
    wb = Path(rep.elf).parent / "weights.bin"
    if wb.is_file():   # the blob netload streams to the board, beside the ELF
        shutil.copy2(wb, out / "weights.bin")
    log(f"built {rep.elf} -> {elf} ({elf.stat().st_size:,} B; weights.bin "
        f"{wb.stat().st_size if wb.is_file() else -1:,} B)")
    return 0


if __name__ == "__main__":
    try:
        rc = main()
    except Exception:
        import traceback
        traceback.print_exc()
        rc = 1
    print(f"GATE_RC={rc}", flush=True)
    sys.exit(rc)
