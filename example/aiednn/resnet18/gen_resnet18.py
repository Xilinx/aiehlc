"""int8 ResNet-18 (TVM's deployed graph) -> the data the aiednn ResNet-18 app runs.

    python3 example/aiednn/resnet18/gen_resnet18.py [--deploy DIR] [--out DIR]
"""
import argparse
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(REPO / "src" / "aietensorop" / "resnetengine"))
import gen_engine as ge  # noqa: E402


def quantize(image, scale: str, zp: str, pad: int) -> np.ndarray:
    """TVM call 00 + zero-point pad: roundf(x * s) + zp, clamp [0, 255], - 128, into [3][230][230] bordered by *pad*."""
    x = image.reshape(3, 224, 224).astype(np.float32) * np.float32(float(scale.rstrip("f")))
    r = (np.sign(x) * np.floor(np.abs(x) + np.float32(0.5))).astype(np.float32)
    v = np.clip(r + np.float32(float(zp.rstrip("f"))), 0, 255).astype(np.int32) - 128
    out = np.full((3, 230, 230), pad, np.int8)
    out[:, 3:227, 3:227] = v.astype(np.int8)
    return out


def i32(a) -> str:
    vals = [int(v) for v in np.asarray(a).reshape(-1)]
    assert all(-2**31 <= v < 2**31 for v in vals), "constant does not fit int32"
    return ", ".join(map(str, vals))


def comb_fields(L) -> str:
    c = L["comb"]
    if c is None:
        return "0, 0, 0, 0, 0, 0, 0, 0"
    return (f"{c['szp']}, {c['sl']}, {c['sM']}LL, {c['ss']}, "
            f"{c['rzr']}, {c['rl']}, {c['rM']}LL, {c['rs']}")


def emit(out: Path, stem, layers, outs, x1, tail) -> None:
    wblob, gold, arrays, rows = bytearray(), bytearray(), [], []

    def put_w(W):
        off = len(wblob)
        wblob.extend(np.ascontiguousarray(W).astype(np.int8).tobytes())
        return off

    def put_arr(name, a):
        arrays.append(f"static const int32_t {name}[] = {{{i32(a)}}};")
        return name

    stem_w = put_w(stem["W"])
    gold.extend(x1.astype(np.uint8).tobytes())
    for i, L in enumerate(layers):
        p = f"r18_l{i:02d}"
        w = put_w(L["W"])
        bz, mu, sh = (put_arr(f"{p}_{k}", L[k]) for k in ("bz", "mult", "shift"))
        d = L["down"]
        if d is not None:
            dw = put_w(d["W"])
            dbz, dmu, dsh = (put_arr(f"{p}_d{k}", d[k]) for k in ("bz", "mult", "shift"))
            dc0 = d["c0"]
        else:
            dw, dbz, dmu, dsh, dc0 = -1, "nullptr", "nullptr", "nullptr", 0
        goff = len(gold)
        gold.extend(outs[L["call"]].astype(np.uint8).tobytes())
        hin = L["Ho"] * L["S"]
        rows.append(f"    {{{L['call']}, {L['Cin']}, {L['Cout']}, {L['S']}, {hin}, {L['Ho']}, {L['Wo']}, "
                    f"{w}L, {bz}, {mu}, {sh}, {L['c0']}, {dw}L, {dbz}, {dmu}, {dsh}, {dc0}, "
                    f"{int(L['grab'])}, {int(L['comb'] is not None)}, {int(L['res_from_down'])}, "
                    f"{comb_fields(L)}, {goff}L}},")
    (out / "r18_weights.bin").write_bytes(bytes(wblob))
    (out / "r18_gold.bin").write_bytes(bytes(gold))
    (out / "r18_image.bin").write_bytes(tail["image"].astype(np.float32).tobytes())
    (out / "r18_logits.bin").write_bytes(tail["logits"].astype(np.float32).tobytes())
    dense = tail["dense_w"]                                       # [N/8][K][8] -> [N][K]
    nk = dense.transpose(0, 2, 1).reshape(-1, dense.shape[1])
    (out / "r18_dense.bin").write_bytes(nk.astype(np.int8).tobytes())
    fq = tail["fq"]
    lut = [int(((v << fq["l"]) * fq["M"] + (1 << (fq["s"] - 1))) >> fq["s"]) for v in range(256)]
    h = ["/* Generated by example/aiednn/resnet18/gen_resnet18.py. Do not edit. */",
         "#ifndef RESNET18_NET_H", "#define RESNET18_NET_H", "#include <stdint.h>", ""]
    for k in ("weights", "dense", "image", "logits", "gold"):
        h.append(f'#define R18_{k.upper()}_PATH "{(out / f"r18_{k}.bin").resolve()}"')
    h += [f"#define R18_Q_SCALE {tail['q_scale']}", f"#define R18_Q_ZP {tail['q_zp']}",
          f"#define R18_Q_PAD {tail['q_pad']}", f"#define R18_NLAYERS {len(layers)}",
          f"#define R18_NCLASS {nk.shape[0]}", f"#define R18_FEAT {nk.shape[1]}",
          f"#define R18_DENSE_C0 {tail['dense_c0']}", f"#define R18_DENSE_ZP {tail['dense_zp']}",
          f"#define R18_DENSE_SCALE {tail['dense_scale']}",
          f"#define R18_STEM_W_OFF {stem_w}L", f"#define R18_STEM_C0 {stem['c0']}",
          f"#define R18_STEM_COUT {stem['W'].shape[0]}", f"#define R18_STEM_CIN {stem['W'].shape[1]}",
          f"#define R18_GOLD_BYTES {len(gold)}", ""]
    h += arrays
    h += [f"static const int32_t r18_stem_bz[] = {{{i32(stem['bz'])}}};",
          f"static const int32_t r18_stem_mult[] = {{{i32(stem['mult'])}}};",
          f"static const int32_t r18_stem_shift[] = {{{i32(stem['shift'])}}};",
          f"static const int32_t r18_dense_bz[] = {{{i32(tail['dense_bz'])}}};",
          f"static const int32_t r18_dense_mult[] = {{{i32(tail['dense_mult'])}}};",
          f"static const int32_t r18_dense_shift[] = {{{i32(tail['dense_shift'])}}};",
          "/* avgpool input = Q(v << l, M) of the last layer's 8-bit output */",
          f"static const int32_t r18_final_lut[256] = {{{i32(lut)}}};", "",
          "typedef struct {",
          "    int call, Cin, Cout, S, Hin, Ho, Wo;  /* Hin: unpadded input; the 3x3 reads it padded by 1 */",
          "    long w_off;                           /* OIHW [Cout][Cin][3][3] in r18_weights.bin */",
          "    const int32_t *bz, *mult, *shift;",
          "    int c0;",
          "    long dw_off;                          /* -1: no fused 1x1 s2 downsample */",
          "    const int32_t *dbz, *dmult, *dshift;",
          "    int dc0, grab, comb, res_from_down;",
          "    int szp, sl; long long sM; int ss;    /* comb: clip(Q(v - szp) + Q(res - rzr)) */",
          "    int rzr, rl; long long rM; int rs;",
          "    long gold_off;                        /* uint8 [Cout][Ho][Wo] in r18_gold.bin */",
          "} r18_layer_t;", "",
          "static const r18_layer_t r18_layers[R18_NLAYERS] = {"] + rows + ["};", "", "#endif", ""]
    (out / "resnet18_net.h").write_text("\n".join(h))
    print(f"wrote {out}/resnet18_net.h + blobs: weights {len(wblob) / 1e6:.1f} MB, gold {len(gold) / 1e6:.1f} MB")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--deploy", default=str(REPO / "worklocal" / "tvmrelay_deploy"))
    ap.add_argument("--out", default=str(REPO / "worklocal" / "aiednn" / "resnet18_data"))
    a = ap.parse_args(argv)
    net = ge.Net(Path(a.deploy))
    layers = ge.build_layers(net)
    stem = ge.build_stem(net)
    x1, _ = ge.model_stem(net, stem)
    outs = ge.model_network(net, layers)          # raises on any mismatch vs TVM
    tail = ge.cpu_tail(net, layers[-1])
    want = ge.dump(net.deploy, 1, "in")[0][0, 0].transpose(2, 0, 1)
    got = quantize(tail["image"], tail["q_scale"], tail["q_zp"], tail["q_pad"])
    bad = int((got != want).sum())
    print(f"  quantize (call 00) + pad vs call 01's input: {'OK' if bad == 0 else f'{bad} MISMATCH'}")
    if bad:
        raise SystemExit("quantize model mismatch")
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    emit(out, stem, layers, outs, x1, tail)
    return 0


if __name__ == "__main__":
    sys.exit(main())
