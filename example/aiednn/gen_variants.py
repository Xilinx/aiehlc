"""Instantiate the AIEDNN library kernel gemm_kacc (src/aiednn/gemm/gemm_kacc_kernel.cc) for a list of layers.

The kernel is ONE C++ template, gemm_kacc<CH, KDIM, PX, KW, AROWS, BROWS, TKW, KCH, NKC, NT, S, TR>; aiehlc
instantiates it at each launch, and every port shape and loop bound becomes a compile-time constant there
(they are the DMA windows and buffer descriptors), so one argument set is one compiled kernel. This script
does what the library's callers (aiegraph cnn.py / cnn_chunk.py) do: pick the walk geometry of each layer
(aiegraph.cnn_chunk.kacc_geom, refusing shapes the kernel cannot cover), turn it into the template arguments
(aiednn.gemm_kacc_launch), de-duplicate identical sets, and write ONE source that holds the template once and
launches every distinct instance (aiehlc compiles one kernel per instance, same TU), plus a dispatch table
(layer -> instance).

    python3 example/aiednn/gen_variants.py --out /tmp/variants            # the demo layer list
    python3 example/aiednn/gen_variants.py --out DIR --layers layers.json  # [{"m": px, "n": ch, "k": K}, ...]

Check / build the program like any example (absolute path; aout/ lands in the cwd):
    build/aiehlc-convtile trace $DIR/gemm_kacc_variants.cc
    source script/aiehlc.sh --aie-version 5 --runtime-source-file $DIR/gemm_kacc_variants.cc
The host part is launch-only (no data, no check): the operand layout (pre-tiled bf16 in int32 words) is the
host contract of the aiegraph builds (src/aiednn/conv2d/kacc_conv_host.cc).
"""
import argparse
import json
import pathlib
import sys

REPO = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))
import aiednn  # noqa: E402
from aiegraph.cnn_chunk import kacc_geom  # noqa: E402
from aiegraph.errors import AiegraphError  # noqa: E402

KERNEL = "gemm/gemm_kacc_kernel.cc"

DEMO_LAYERS = [  # (M pixels, N channels, K = Cin*kh*kw) -- conv layers as im2col GEMMs
    {"m": 256, "n": 64, "k": 576},
    {"m": 256, "n": 64, "k": 576},     # same shape again: re-uses instance 0
    {"m": 256, "n": 128, "k": 576},
    {"m": 64, "n": 128, "k": 1152},
]

HEAD = """// gemm_kacc_variants.cc -- generated by example/aiednn/gen_variants.py: the aiednn gemm_kacc template
// (src/aiednn/gemm/gemm_kacc_kernel.cc, verbatim) + one launch per distinct instance (%d), launch-only host.
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    ap.add_argument("--layers", help="JSON list of {m, n, k}; default: the demo list")
    a = ap.parse_args()
    layers = json.loads(pathlib.Path(a.layers).read_text()) if a.layers else DEMO_LAYERS
    out = pathlib.Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    variants, table = {}, []   # (ch, k, px) -> (index, callee)
    for i, layer in enumerate(layers):
        ch, k, px = layer["n"], layer["k"], layer["m"]
        try:
            g = kacc_geom(ch, k, px)
        except AiegraphError as e:
            raise SystemExit(f"layer {i}: M={px} N={ch} K={k}: {e}")
        key = (ch, k, px)
        if key not in variants:
            variants[key] = (len(variants), aiednn.gemm_kacc_launch(ch, k, px, g))
        idx, callee = variants[key]
        table.append({"layer": i, "instance": idx, "callee": callee, "m": px, "n": ch, "k": k, "kp": g["kp"]})
        print(f"layer {i}: M={px} N={ch} K={k} -> instance {idx} {callee} (K chunk {g['kch']}, "
              f"{g['nkc']} chunks, padded K {g['kp']})")
    disp = "\n".join(f"    if (which == {idx}) {{\n        {callee}<<<mesh>>>(w, x, y);\n        return 0;\n    }}"
                     for idx, callee in variants.values())
    words = max(max(ch, px) * kacc_geom(ch, k, px)["kp"] // 2 for ch, k, px in variants)
    outw = max(ch * px for ch, k, px in variants)
    host = f"""

static int variant_launch(int which, int32_t *w, int32_t *x, int32_t *y) {{
    aieSetDevice(0);
    aieArray device;
    aieMesh mesh = device.partition({{2, 6, 0, 6}}, 4, 4);
{disp}
    return -1;
}}

int main() {{
    int32_t *Wd = (int32_t *)__Runtime_Alloc({words} * 4);
    int32_t *Xd = (int32_t *)__Runtime_Alloc({words} * 4);
    int32_t *Yd = (int32_t *)__Runtime_Alloc({outw} * 4);
    for (int i = 0; i < {len(variants)}; i++)
        variant_launch(i, Wd, Xd, Yd);
    printf("gemm_kacc_variants: {len(variants)} instances launched\\n");
    return 0;
}}
"""
    (out / "gemm_kacc_variants.cc").write_text(HEAD % len(variants) + aiednn.template(KERNEL) + host)
    (out / "dispatch.json").write_text(json.dumps(table, indent=1) + "\n")
    print(f"{len(layers)} layers -> {len(variants)} instances in {out / 'gemm_kacc_variants.cc'} "
          f"(dispatch.json: layer -> instance)")


if __name__ == "__main__":
    main()
